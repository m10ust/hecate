# Tilde in a remote destination refers to the REMOTE home; ssh passes $1
# verbatim (no expansion), so every probe expands it itself, remote-side.
EXPAND_TILDE = 'd="$1"; case "$d" in "~"*) d="$HOME${d#\\~}";; esac; '

# One remote probe, passed as a single argument (no nested quoting): the
# destination path rides as $1, so a path with spaces or quotes cannot
# escape. Prints KEY=VALUE lines, sh-compatible.
# M4: adds model=/serial=/transport= — the remote device identity, read
# the same walk-up-the-ancestry way as the local side (partition -> disk).
# Values are sanitized on the Python side after parsing, never here.
SSH_IDENTITY_PROBE = (
    EXPAND_TILDE
    + 'if [ ! -e "$d" ]; then echo "missing=1"; exit 3; fi; '
    'echo "dev=$(stat -c %d "$d" 2>/dev/null)"; '
    'echo "uuid=$(findmnt -T "$d" -n -o UUID 2>/dev/null)"; '
    'echo "source=$(findmnt -T "$d" -n -o SOURCE 2>/dev/null)"; '
    'echo "fstype=$(findmnt -T "$d" -n -o FSTYPE 2>/dev/null)"; '
    'echo "machine=$(cat /etc/machine-id 2>/dev/null)"; '
    # device identity walk: SOURCE node -> (strip btrfs subvol suffix)
    # -> dm slaves (a crypt node parents nothing in lsblk; its physical
    # parent lives in /sys/class/block/dm-*/slaves) -> PKNAME chain,
    # until a node reports a MODEL. tmpfs/NFS sources exit quietly.
    'src=$(findmnt -T "$d" -n -o SOURCE 2>/dev/null); '
    'case "$src" in /dev/*) ;; *) exit 0;; esac; '
    'src=${src%%[*}; '
    'lsblk -s -p -n -r -o NAME,TYPE "$src" 2>/dev/null | '
    'while read -r device kind; do [ "$kind" = disk ] && echo "physical=$device"; done; '
    'node=$(readlink -f "$src" 2>/dev/null || echo "$src"); '
    'while [ -n "$node" ]; do '
    '  j=$(lsblk -J -d -n -o MODEL,SERIAL,TRAN "$node" 2>/dev/null); '
    '  m=$(printf "%s" "$j" | grep -o \'"model": "[^"]*"\' | head -1 | sed \'s/.*: //;s/"//g\'); '
    '  if [ -n "$m" ]; then '
    '    echo "model=$m"; '
    '    s=$(printf "%s" "$j" | grep -o \'"serial": "[^"]*"\' | head -1 | sed \'s/.*: //;s/"//g\'); '
    '    [ -n "$s" ] && echo "serial=$s"; '
    '    t=$(printf "%s" "$j" | grep -o \'"transport": "[^"]*"\' | head -1 | sed \'s/.*: //;s/"//g\'); '
    '    [ -n "$t" ] && echo "transport=$t"; '
    '    exit 0; '
    '  fi; '
    '  b=$(basename "$node"); '
    '  case "$b" in dm-*) '
    '    p=$(ls /sys/class/block/$b/slaves 2>/dev/null | head -1); '
    '    node=""; [ -n "$p" ] && node="/dev/$p"; '
    '  ;; *) '
    '    p=$(lsblk -J -d -n -o PKNAME "$node" 2>/dev/null | grep -o \'"pkname": "[^"]*"\' | head -1 | sed \'s/.*: //;s/"//g\'); '
    '    node=""; [ -n "$p" ] && node="/dev/$p"; '
    '  esac; '
    'done'
)


def _clean_id_value(v) -> str | None:
    """One line, no control characters, not empty. Identity values cross
    a ssh pipe and a JSON file; both deserve clean text."""
    if v is None:
        return None
    first = str(v).splitlines()
    if not first:
        return None
    v = "".join(ch for ch in first[0] if ord(ch) >= 32).strip()
    return v or None


def block_node_of(source: str) -> str | None:
    """The block node for a findmnt SOURCE, or None for non-block sources
    (tmpfs, NFS). Strips btrfs subvolume suffixes and maps a /dev/mapper
    name to its /dev/dm-N node so the ancestry walk starts at a node
    /sys/class/block actually lists."""
    if not source or not source.startswith("/dev/"):
        return None
    node = source.split("[", 1)[0]
    try:
        resolved = os.path.realpath(node)
        if resolved.startswith("/dev/"):
            node = resolved  # /dev/mapper/root -> /dev/dm-0
    except OSError:
        pass
    b = node.rsplit("/", 1)[-1]
    if b.startswith("dm-") or node.startswith("/dev/dm-"):
        return node
    dm = Path("/sys/class/block") / b / "dm"
    if dm.is_dir():  # mapper name (root) -> dm-N
        name = (dm / "name").read_text().strip()
        if name:
            for e in Path("/sys/class/block").iterdir():
                if e.name.startswith("dm-") and (e / "dm" / "name").exists():
                    try:
                        if (e / "dm" / "name").read_text().strip() == name:
                            return f"/dev/{e.name}"
                    except OSError:
                        continue
    return node


def _lsblk_fields(node: str, cols: str) -> dict | None:
    """lsblk -J -d -n -o <cols> for one node, parsed from JSON. None on
    any failure. JSON because -n prints EMPTY LINES for null fields, and
    a naive split shifts columns (partition rows inherit TRAN but not
    MODEL — exactly the trap that reports a transport as a model)."""
    try:
        proc = subprocess.run(
            ["lsblk", "-J", "-d", "-n", "-o", cols, node],
            capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return None
    if proc.returncode != 0:
        return None
    try:
        dev = json.loads(proc.stdout)["blockdevices"][0]
    except (json.JSONDecodeError, KeyError, IndexError, TypeError):
        return None
    return dev if isinstance(dev, dict) else None


def udev_ident(source: str | None) -> dict:
    """Model, serial and transport of the DISK backing a mount source,
    read from the udev database via lsblk, walking up the ancestry:
    partition -> disk, and through device-mapper slaves (a LUKS crypt
    node parents nothing in lsblk; its physical parent is in
    /sys/class/block/dm-*/slaves). Returns {} when no model can be read —
    unknown with the reason is the CALLER's job, this only reads."""
    node = block_node_of(source or "")
    while node:
        b = node.rsplit("/", 1)[-1]
        # a dm node's parent is its slave, not PKNAME (which is empty)
        parent = None
        if b.startswith("dm-"):
            try:
                slaves = list((Path("/sys/class/block") / b / "slaves").iterdir())
                parent = f"/dev/{slaves[0].name}" if slaves else None
            except OSError:
                parent = None
        dev = _lsblk_fields(node, "MODEL,SERIAL,TRAN")
        if dev is not None:
            model = _clean_id_value(dev.get("model"))
            if model:
                return {"model": model,
                        "serial": _clean_id_value(dev.get("serial")),
                        "transport": _clean_id_value(dev.get("tran")) or None}
        if parent is None:
            pkdev = _lsblk_fields(node, "PKNAME")
            pk = _clean_id_value(pkdev.get("pkname")) if pkdev else None
            parent = f"/dev/{pk}" if pk else None
        node = parent
    return {}


def physical_disks(source: str) -> list:
    """All physical ancestors, including every member of a mapper/RAID tree."""
    node = block_node_of(source)
    if not node:
        return []
    try:
        proc = subprocess.run(["lsblk", "-s", "-p", "-J", "-o", "NAME,TYPE", node],
                              capture_output=True, text=True, timeout=10)
        if proc.returncode:
            return []
        roots = json.loads(proc.stdout)["blockdevices"]
    except (OSError, subprocess.SubprocessError, ValueError, KeyError):
        return []
    disks = set()
    def visit(entry):
        if entry.get("type") == "disk" and entry.get("name"):
            disks.add(os.path.realpath(entry["name"]))
        for child in entry.get("children", []):
            visit(child)
    for entry in roots:
        visit(entry)
    return sorted(disks)


def findmnt_of(path: Path):
    """UUID/SOURCE/FSTYPE for the filesystem holding path, or None."""
    try:
        proc = subprocess.run(
            ["findmnt", "-J", "-T", str(path), "-o", "UUID,SOURCE,FSTYPE"],
            capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return None
    if proc.returncode != 0 or not proc.stdout.strip():
        return None
    try:
        fs = json.loads(proc.stdout)["filesystems"][0]
    except (ValueError, KeyError, IndexError):
        return None
    return {"uuid": fs.get("uuid"), "source": fs.get("source", ""), "fstype": fs.get("fstype", "")}


FSTYPES_THAT_LACK_UUID = {"tmpfs", "devtmpfs", "swap", "proc", "sysfs",
                          "cgroup", "cgroup2", "overlay"}


def read_local_identity(path) -> dict:
    """Identity of a local path: st_dev always; filesystem UUID where
    findmnt can read it (the stronger check). Unreadable -> a dict that
    SAYS so; never a silent pass."""
    p = Path(path).expanduser().resolve()
    try:
        if not p.is_dir():
            return {"unreadable": f"destination not present: {p}"}
        st = os.stat(p)
    except OSError as e:
        return {"unreadable": f"{type(e).__name__}: {e}"}
    ident = {"dev": st.st_dev, "path": str(p)}
    try:
        ident["machine"] = Path("/etc/machine-id").read_text().strip()
    except OSError:
        pass
    fs = findmnt_of(p)
    if fs:
        if fs["uuid"]:
            ident["fsuuid"] = fs["uuid"]
        ident["fssource"] = fs["source"]
        ident["fstype"] = fs["fstype"]
        ident["physical"] = physical_disks(fs["source"])
        # M4: the sibling warning bites on real hardware — model/serial/
        # transport of the DISK behind the mount, read never guessed.
        if fs["fstype"] == "tmpfs" or fs["source"].startswith(("tmpfs", "none")):
            ident["identityNote"] = f"tmpfs: no physical device carries this filesystem"
        else:
            udev = udev_ident(fs["source"])
            if udev.get("model"):
                ident["model"] = udev["model"]
                if udev.get("serial"):
                    ident["serial"] = udev["serial"]
                if udev.get("transport"):
                    ident["transport"] = udev["transport"]
            else:
                ident["identityNote"] = (
                    f"model/serial unreadable for backing device of {fs['source']} "
                    "(no ancestor with a model in the block ancestry)")
    if not ident.get("physical") or not ident.get("machine"):
        ident["unreadable"] = ident.get("identityNote") or "physical backing device or machine identity unreadable"
    return ident


def parse_ssh_dest(dest: str):
    """'host:/path' -> (host, path). Refuses shapes it cannot split."""
    if ":" not in dest:
        return None, f"ssh destination is not host:/path: {dest!r}"
    host, path = dest.split(":", 1)
    if not host or not path:
        return None, f"ssh destination is not host:/path: {dest!r}"
    return host, path


def resolve_remote_home(host: str) -> str | None:
    """Absolute remote home dir, read once via ssh. Needed because rsync
    only expands a tilde at the very START of the remote path — inside a
    path it is a literal directory named '~' (proven on the bee: rsync
    rc=0 into ~/... as a relative literal). The engine resolves '~' to the
    real remote home itself and never passes a tilde to rsync."""
    try:
        proc = subprocess.run(["ssh", *SSH_OPTS, host, "echo $HOME"],
                              capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    home = (proc.stdout or "").strip().splitlines()
    return home[0].strip() if home and proc.returncode == 0 else None


def posix_quote(s: str) -> str:
    return "'" + s.replace("'", "'\\''") + "'"


def ssh_script(host: str, script: str, args: list, timeout: int = 45):
    """Run a shell script on host with REAL positional parameters.

    ssh joins its command argv into one string for the remote shell, so
    `$1` inside a passed script is always empty. The working pattern is
    `sh -s 'arg'...` with the script on stdin. POSIX detail: with `-s`
    there is NO $0 operand — the first operand binds to $1 directly.
    Operands are single-quoted for the remote login shell (spaces, quotes
    and dollars survive across sh/bash/zsh/dash; a remote shell outside
    the POSIX family would need its own quoting and is out of scope)."""
    cmd = "sh -s " + " ".join(posix_quote(a) for a in args)
    return subprocess.run(
        ["ssh", *SSH_OPTS, host, cmd],
        input=script, capture_output=True, text=True, timeout=timeout)


def read_ssh_identity(dest: str) -> dict:
    host, path = parse_ssh_dest(dest)
    if host is None:
        return {"unreadable": path}
    # resolve a leading ~ to the remote home before probing (rsync law:
    # tilde-inside-a-path is a literal; the engine resolves it itself)
    if path.startswith("~"):
        home = resolve_remote_home(host)
        if home is None:
            return {"unreadable": f"could not resolve remote home on {host} to expand '~' in {dest}"}
        path = home + path[1:]
    try:
        proc = ssh_script(host, SSH_IDENTITY_PROBE, [path])
    except (OSError, subprocess.SubprocessError) as e:
        return {"unreadable": f"ssh probe to {host} failed: {type(e).__name__}: {e}"}
    if proc.returncode == 3 and "missing=1" in proc.stdout:
        return {"unreadable": f"remote destination not present: {host}:{path}"}
    if proc.returncode != 0:
        err = (proc.stderr or "").strip().splitlines()
        return {"unreadable": f"ssh probe to {host} exited {proc.returncode}"
                             + (f": {err[-1][:200]}" if err else "")}
    ident: dict = {"host": host, "path": path}
    for line in proc.stdout.splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            if k == "dev" and v.strip().isdigit():
                ident["dev"] = int(v.strip())
            elif k == "uuid" and v.strip():
                ident["fsuuid"] = v.strip()
            elif k == "source" and v.strip():
                ident["fssource"] = v.strip()
            elif k == "fstype" and v.strip():
                ident["fstype"] = v.strip()
            elif k == "model" and v.strip():
                ident["model"] = _clean_id_value(v)
            elif k == "serial" and v.strip():
                ident["serial"] = _clean_id_value(v)
            elif k == "transport" and v.strip():
                ident["transport"] = _clean_id_value(v)
            elif k == "machine" and v.strip():
                ident["machine"] = v.strip()
            elif k == "physical" and v.strip():
                ident.setdefault("physical", []).append(v.strip())
    if "dev" not in ident:
        return {"unreadable": f"ssh probe to {host} returned no device id for {path}"}
    ident["physical"] = sorted(set(ident.get("physical", [])))
    if not ident.get("machine") or not ident.get("physical"):
        ident["unreadable"] = f"physical backing device or machine identity unreadable on {host}"
    return ident


def corner_identity(c: dict) -> dict:
    """Identity for a declared corner, by transport. Cloud corners are
    declare-and-warn by nature (L1) and carry no filesystem identity."""
    transport = c.get("transport", "local")
    dest = str(c.get("destination", ""))
    if transport == "local":
        return read_local_identity(dest)
    if transport == "ssh":
        return read_ssh_identity(dest)
    return {"cloud": f"{transport} corner: account and provider failures cannot be measured as filesystem identity"}


def destination_observation(c: dict) -> dict:
    """Live read facts, never written to state by a probe. Identity beats existence."""
    dest = c.get("destination", "")
    if c.get("transport", "local") == "local":
        try:
            os.stat(Path(dest).expanduser())
        except FileNotFoundError:
            return {"present": False, "reason": f"destination not present: {dest}"}
        except OSError as e:
            return {"present": None, "reason": f"{type(e).__name__}: {e}"}
    actual = corner_identity(c)
    if actual.get("unreadable"):
        return {"present": None, "reason": actual["unreadable"]}
    expected = c.get("identity")
    if not expected:
        return {"present": None, "reason": "destination identity not recorded"}
    # USB enumeration can change /dev/sdX after a replug. Prefer the recorded
    # hardware serial when available; filesystem UUID alone cannot identify
    # the disk (a clone can preserve it).
    keys = ("machine", "fsuuid", "serial") if expected.get("serial") else ("machine", "fsuuid", "physical")
    for key in keys:
        if expected.get(key) and not actual.get(key):
            return {"present": None, "reason": f"destination backing identity unreadable: {key}"}
        if expected.get(key) and expected.get(key) != actual.get(key):
            return {"present": False if c.get("transport", "local") == "local" else None,
                    "reason": f"destination backing identity changed: {key} expected={expected.get(key)} actual={actual.get(key)}"}
    return {"present": True, "reason": "", "identity": actual}


def power_group(ident: dict, transport: str):
    """The shared-power key for the sibling warning. One machine is one
    power path: both local corners draw from this box, both corners on one
    ssh host draw from that box."""
    if ident.get("power"):
        return ident["power"]
    if ident.get("machine"):
        return f"machine:{ident['machine']}"
    if ident.get("host"):
        return f"ssh:{ident['host']}"
    if transport == "local":
        return "local:one-machine"
    return None


def model_of(ident: dict):
    return ident.get("model")


def same_filesystem(a: dict, b: dict):
    """(same?, evidence). UUID is the stronger check where readable; st_dev
    is the fallback, and only between two paths read from the SAME kernel:
    st_dev is a per-boot allocation, so equality across hosts is coincidence
    (rig /tmp and bee /tmp have both been dev 57 on this fleet). Cross-host
    pairs fall back to the UUID comparison; without readable UUIDs they are
    simply not provably same, and a refusal must rest on evidence, not on
    coincidence. Identity carries 'host' for ssh reads; local reads have
    none, so equal-host (including both-absent) means one kernel."""
    if a.get("machine") and a.get("machine") == b.get("machine"):
        overlap = set(a.get("physical", [])) & set(b.get("physical", []))
        if overlap:
            return True, f"same physical backing disk {sorted(overlap)}"
    if a.get("model") and a.get("model") == b.get("model") and a.get("serial") and a.get("serial") == b.get("serial"):
        return True, f"same physical disk serial {a['serial']} (model {a['model']})"
    if a.get("fsuuid") and b.get("fsuuid"):
        if a["fsuuid"] == b["fsuuid"]:
            return True, f"same filesystem UUID {a['fsuuid']}"
        return False, f"filesystem UUIDs differ ({a['fsuuid']} vs {b['fsuuid']})"
    # M5.5: the backing-disk key closes the btrfs subvolume seam — one
    # disk, one UUID, DIFFERENT st_dev per subvolume (the bee: / is dev
    # 32, /home is dev 30, both /dev/mapper/root[/@...] — refused by UUID
    # above; this lane catches the same geometry when UUIDs are absent).
    same_machine = (a.get("machine") == b.get("machine") if a.get("machine") and b.get("machine")
                    else a.get("host") == b.get("host"))
    ka, kb = backed_disk_key(a), backed_disk_key(b)
    if same_machine and ka and kb:
        if ka == kb:
            return True, f"same backing disk ({ka}; btrfs subvolumes share one disk)"
        return False, f"backing disks differ ({ka} vs {kb})"
    if (same_machine
            and a.get("dev") is not None and b.get("dev") is not None):
        if a["dev"] == b["dev"]:
            return True, f"same device id (st_dev {a['dev']}; UUID unreadable on at least one side)"
    return False, ""


