def cmd_schedule_set(name: str, calendar: str | None, on_off: str | None) -> int:
    """Set/replace a job's schedule (calendar string or the 02:00
    default), arm or disarm its timer, and record facts. The wizard's
    schedule screen and the panel both land here; the engine stays the
    only writer."""
    state = read_state()
    job, idx = find_job(state, name)
    if job is None:
        print(f"hecate: no such job '{name}'", file=sys.stderr)
        return 2
    sched = job.setdefault("schedule", {})
    changed_calendar = False
    if calendar is not None:
        ok, norm_or_err = validate_calendar(calendar)
        if not ok:
            print(f"hecate: {norm_or_err}", file=sys.stderr)
            return 2
        if sched.get("calendar") != norm_or_err:
            changed_calendar = True
        sched["calendar"] = norm_or_err
    if on_off is not None:
        on_off = on_off.lower()
        if on_off not in ("on", "off"):
            print("hecate: --on-off expects 'on' or 'off'", file=sys.stderr)
            return 2
        sched["enabled"] = on_off == "on"
    if sched.get("enabled", False):
        facts = write_job_timer(job, sys.executable or "python3")
        job["timer"] = facts
        if not facts.get("written") or facts.get("error"):
            print(f"hecate: units written but activation failed: {facts.get('error')}")
            rc = 1
        else:
            print(f"hecate: timer armed for '{name}'  OnCalendar={facts.get('calendar')}  "
                  f"Persistent=true")
            rc = 0
        # the AIDE announce rides every arming (addendum §2): how the
        # pre-write announcement traveled is part of the arm receipt
        a = facts.get("announce", "")
        if a == "noted":
            print(f"hecate: AIDE note filed: {facts.get('announceCause')}")
        elif a == "degraded":
            print(f"hecate: AIDE note lane unusable ({facts.get('announceCause')}) — "
                  f"announcement recorded in state and journald")
        elif a == "absent":
            print("hecate: AIDE not present; announcement rides journald + state")
    else:
        facts = remove_job_timer(name)
        job["timer"] = None
        if not facts.get("removed"):
            print(f"hecate: disarm incomplete: {facts.get('error')}")
            rc = 1
        else:
            print(f"hecate: timer disarmed for '{name}' (units removed)")
            rc = 0
    state["jobs"][idx] = job
    write_state(state)
    if changed_calendar:
        print(f"hecate: calendar replaced (a changed schedule replaces its units)")
    return rc


def validate_calendar(cal: str) -> tuple:
    """(ok, normalized-or-error). systemd-analyze calendar is the
    authority; the engine refuses to write a calendar it cannot check."""
    try:
        proc = subprocess.run(["systemd-analyze", "calendar", cal],
                              capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError) as e:
        return False, f"cannot validate calendar ({type(e).__name__}: {e})"
    if proc.returncode != 0:
        err = [str(x) for x in (proc.stderr or "").strip().splitlines()]
        return False, ("invalid calendar: " + (err[-1] if err else f"exit {proc.returncode}"))[:250]
    for line in (proc.stdout or "").splitlines():
        if line.startswith("Normalized form: "):
            return True, line[len("Normalized form: "):].strip()
    return True, cal


def cmd_timers() -> int:
    """Timer census: what the engine's state says vs what systemd holds —
    the two-source truth, printed, plus the raw list-timers receipt."""
    state = read_state()
    print("jobs with schedules (state file):")
    any_ = False
    for job in state.get("jobs", []):
        sched = job.get("schedule") or {}
        if not sched:
            continue
        any_ = True
        t = job.get("timer") or {}
        print(f"  {job.get('name')}: enabled={sched.get('enabled')} "
              f"calendar={sched.get('calendar')} "
              f"units={'written' if t.get('written') else 'not written'} "
              f"activated={'yes' if t.get('enabled') else 'no'}"
              + (f"  error={t.get('error')}" if t.get("error") else ""))
    if not any_:
        print("  (none — unconfigured is a quiet no-op)")
    print("systemd --user list-timers 'hecate-' (live):")
    env = dict(os.environ)
    env.setdefault("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}")
    try:
        proc = subprocess.run(["systemctl", "--user", "list-timers", "hecate-*",
                               "--no-pager", "--all"],
                              capture_output=True, text=True, timeout=30, env=env)
        for line in (proc.stdout or "").splitlines():
            print(f"  {line}")
        if proc.returncode:
            print(f"  list-timers exit={proc.returncode}: {(proc.stderr or '').strip()}")
            return 4
    except (OSError, subprocess.SubprocessError) as e:
        print(f"  (list-timers unreadable: {type(e).__name__}: {e})")
        return 4
    return 0


