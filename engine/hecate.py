def measure(path: Path) -> dict:
    """Byte total and file count by walking the tree. Symlinks count as
    files at their lstat size."""
    files, total = 0, 0
    if (path / MANIFEST_NAME).exists() or (path / MANIFEST_NAME).is_symlink():
        raise ValueError(f"reserved snapshot manifest path exists in source: {path / MANIFEST_NAME}")
    def fail(error):
        raise error
    for root, dirs, names in os.walk(path, onerror=fail):
        dirs.sort()
        for n in names:
            files += 1
            total += os.lstat(os.path.join(root, n)).st_size
    return {"bytes": total, "files": files}


def file_list_ssh(host: str, tree: str):
    """file_list() for a remote tree, via `rsync --list-only`. Returns a
    sorted list of relative paths, or None when the listing itself failed
    (the caller records unknown, never a silent pass)."""
    try:
        proc = subprocess.run(
            ["rsync", "--list-only", "-e", RSYNC_E, f"{host}:{tree}/"],
            capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError) as e:
        return None
    if proc.returncode != 0:
        return None
    out = []
    for line in proc.stdout.splitlines():
        parts = line.split(None, 4)
        if len(parts) < 5 or parts[0].startswith("d"):
            continue
        out.append(parts[4])
    out.sort()
    return out


# ---------------------------------------------------------------------------
# the run lock — one engine run per job, ever (M5). A timer firing while a
# clicked run holds the job must not interleave snapshots or race the state
# file; the loser exits quietly with a printed fact, never a second writer.
# ---------------------------------------------------------------------------


def _runtime_dir() -> Path:
    # XDG_RUNTIME_DIR is the correct per-user, tmpfs-backed home for locks;
    # fall back to the state dir when it is unset (cron seats without a
    # session), so the lock never silently lives on disk another user owns
    xdg = os.environ.get("XDG_RUNTIME_DIR")
    base = Path(xdg) if xdg else state_dir()
    p = base / "hecate"
    p.mkdir(parents=True, exist_ok=True)
    return p


def acquire_run_lock(name: str, shared: bool = False, wait: bool = False):
    """(fd, path) or (None, reason). fcntl.flock, held for process life."""
    import fcntl
    path = _runtime_dir() / ("state.lock" if shared else f"run-{name}.lock")
    fd = os.open(path, os.O_RDWR | os.O_CREAT, 0o600)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX | (0 if wait else fcntl.LOCK_NB))
    except OSError:
        os.close(fd)
        return None, f"another run of '{name}' is already active (lock {path})"
    os.ftruncate(fd, 0)
    os.write(fd, f"{os.getpid()} {datetime.now().astimezone().isoformat(timespec='seconds')}\n".encode())
    return fd, path


# ---------------------------------------------------------------------------
# typed file lists (M5 Part B): walk once, keep what each entry IS. The
# plain-path list stays the diff unit; the typed entries drive hashing,
# which must skip symlinks (a link's "bytes" are its target's, and rsync -a
# copies links as links — hashing the followed target proves nothing about
# the copy and can walk outside the tree).
# ---------------------------------------------------------------------------


def walk_typed(tree: Path) -> dict:
    """{relpath: "f"|"l"} for everything under tree. Files and symlinks;
    directories are implied by their children. Sorted, deterministic."""
    tree = Path(tree)
    out: dict = {}
    def fail(error):
        raise error
    for root, dirs, names in os.walk(tree, followlinks=False, onerror=fail):
        dirs.sort()
        for n in names:
            rel = os.path.relpath(os.path.join(root, n), tree)
            full = os.path.join(root, n)
            if os.path.islink(full):
                out[rel] = "l"
            elif os.path.isfile(full):
                out[rel] = "f"
            # neither f nor l (fifo, socket, device): rsync -a does not
            # copy them without -D; they are not hashed and the list diff
            # still reports their absence honestly
    return out


def file_list(tree: Path) -> list:
    """Sorted relative paths of everything under tree. The diff unit:
    equal byte totals hide a swapped file; equal lists do not."""
    return sorted(walk_typed(tree).keys())


# ---------------------------------------------------------------------------
# manifests + hashing (M5 Part B). MANIFEST.sha256 lives INSIDE the
# snapshot, `sha256sum -c` compatible, so any corner on any machine carries
# its own proof. Symlinks ride as "l <relpath>" lines — present in the
# receipt, never hashed.
# ---------------------------------------------------------------------------


def hash_tree(tree: Path, files: list, chunk: int = 1 << 20) -> list:
    """[(relpath, sha256)] for each file in `files` (already filtered to
    regular files). Content-hashed; unreadable entries raise (the caller
    records unknown, never a silent pass)."""
    import hashlib
    h_out = []
    for rel in files:
        h = hashlib.sha256()
        with open(os.path.join(tree, rel), "rb") as f:
            while True:
                b = f.read(chunk)
                if not b:
                    break
                h.update(b)
        h_out.append((rel, h.hexdigest()))
    return h_out


def write_manifest(tree: Path, hashed: list, links: list) -> str:
    """Write MANIFEST.sha256 inside tree. sha256sum -c compatible file
    lines first, then `l <relpath>` marker lines for symlinks. Returns
    the manifest's own sha256 (the state file's manifest receipt)."""
    lines = [f"{digest}  {rel}" for rel, digest in hashed] + \
            [f"l  {rel}" for rel in sorted(links)]
    body = ("\n".join(lines) + "\n") if lines else ""
    p = Path(tree) / MANIFEST_NAME
    tmp = p.with_name(p.name + ".tmp")
    with open(tmp, "w") as f:
        f.write(body)
    os.replace(tmp, p)
    import hashlib
    return hashlib.sha256(body.encode()).hexdigest()


def scrub_check_manifest(tree: Path) -> dict:
    """Re-read the snapshot bytes and rehash against MANIFEST.sha256
    inside it. Returns {ok, files, bad, missing, extra} — bad entries
    carry (relpath, expected, actual-or-reason). The manifest itself and
    the `.latest` symlink are snapshot CHROME, not content: never hashed.
    Excludes an absent manifest honestly (ok=False, reason)."""
    tree = Path(tree)
    mp = tree / MANIFEST_NAME
    if not mp.is_file():
        return {"ok": False, "reason": f"no {MANIFEST_NAME} in {tree}"}
    expected: dict = {}
    links: set = set()
    with open(mp) as f:
        for ln, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line:
                continue
            if line.startswith("l  "):
                links.add(line[3:])
                continue
            # sha256sum format: <64 hex>  <relpath>  (two spaces, binary)
            if len(line) < 67 or line[64:66] != "  ":
                return {"ok": False, "reason": f"{MANIFEST_NAME}:{ln}: not a sha256sum line: {line[:60]!r}"}
            expected[line[66:]] = line[:64]
    typed = walk_typed(tree)
    bad, missing = [], []
    import hashlib
    checked = 0
    for rel, digest in sorted(expected.items()):
        if rel == MANIFEST_NAME:
            continue  # chrome: the receipt does not hash itself
        kind = typed.get(rel)
        if kind != "f":
            missing.append(rel)
            continue
        h = hashlib.sha256()
        try:
            with open(os.path.join(tree, rel), "rb") as f:
                while True:
                    b = f.read(1 << 20)
                    if not b:
                        break
                    h.update(b)
        except OSError as e:
            bad.append((rel, digest, f"read failed: {e}"))
            continue
        checked += 1
        if h.hexdigest() != digest:
            bad.append((rel, digest, h.hexdigest()))
    extra = sorted(r for r in typed
                   if r not in expected and r not in links and r != MANIFEST_NAME)
    for rel in sorted(links):
        if rel not in typed:
            missing.append(f"{rel} (symlink)")
    return {"ok": not bad and not missing and not extra and checked == len(expected),
            "files": len(expected), "checked": checked,
            "bad": bad, "missing": missing, "extra": extra}


# ---------------------------------------------------------------------------
# remote hashing (ssh corners): the scrub runs where the bytes are. One
# ssh_script call, no nested quoting, output parsed on this side.
# ---------------------------------------------------------------------------

REMOTE_SCRUB = (
    'd="$1"; m="$d/MANIFEST.sha256"; '
    'test -f "$m" || { echo "ERR no manifest at $m"; exit 3; }; '
    'cd "$d" || exit 4; '
    'n=0; bad=0; '
    # IFS word-splitting collapses the two-space sha256sum separator
    # into one, so read-by-field cannot parse the line: split on the
    # LITERAL double space instead (%% longest prefix, ## longest suffix)
    'while IFS= read -r line; do '
    '  case "$line" in "l  "*) continue;; esac; '
    '  [ -n "$line" ] || continue; '
    '  h=${line%%  *}; rel=${line#*  }; '
    '  [ -n "$h" ] && [ -n "$rel" ] || continue; '
    '  n=$((n+1)); '
    '  c=$(sha256sum -- "$rel" 2>/dev/null | cut -d" " -f1); '
    '  if [ "$c" != "$h" ]; then bad=$((bad+1)); echo "MISMATCH $rel want=$h got=${c:-unreadable}"; fi; '
    'done < "$m"; '
    'echo "SCRUB files=$n bad=$bad"; '
    'test "$bad" -eq 0'
)

def ssh_write_file(host: str, remote_path: str, local_path: Path) -> tuple:
    """(returncode, stderr-tail). The remote target is posix_quote'd into
    a single `cat > 'path'` command; the payload rides ssh's stdin. No
    scp (remote-path quoting differs by scp mode), no rsync (a manifest
    push is not a tree sync)."""
    cmd = f"cat > {posix_quote(remote_path)}"
    try:
        with open(local_path, "rb") as f:
            proc = subprocess.run(["ssh", *SSH_OPTS, host, cmd],
                                  stdin=f, capture_output=True, timeout=120)
    except (OSError, subprocess.SubprocessError) as e:
        return 1, f"{type(e).__name__}: {e}"
    tail = [str(x) for x in (proc.stderr or "").strip().splitlines()]
    return proc.returncode, " | ".join(tail[-2:])[-200:]


# ---------------------------------------------------------------------------
# systemd user timers (M5 Part A). The engine generates one unit pair per
# job: hecate-<job>.service (Type=oneshot, the engine itself with
# --by-timer) and hecate-<job>.timer (OnCalendar=*-*-* 02:00:00,
# Persistent=true so a window missed to sleep fires on wake). No sudo, no
# system units, ever (distribution law). daemon-reload on every write.
# Unconfigured = no units = a quiet no-op.
# ---------------------------------------------------------------------------


def systemd_user_dir() -> Path:
    xdg = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
    return Path(xdg) / "systemd" / "user"


def job_unit_base(name: str) -> str:
    return f"hecate-{name}"


def _atomic_write(path: Path, text: str) -> None:
    tmp = path.with_name(path.name + ".tmp")
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)


SERVICE_UNIT = """\
# generated by hecate v{version} — the engine owns this file; edits are
# overwritten on the next schedule write. Job: {name}
[Unit]
Description=Hecate backup run: {name}

[Service]
Type=oneshot
ExecStart={python} {engine} run {job} --by-timer
# the journald lane is the timer's own receipt trail
StandardOutput=journal
StandardError=journal
"""

TIMER_UNIT = """\
# generated by hecate v{version} — the engine owns this file; edits are
# overwritten on the next schedule write. Job: {name}
[Unit]
Description=Hecate nightly backup timer: {name}

[Timer]
OnCalendar={calendar}
# a window missed to sleep fires on wake: the catch-up promise
Persistent=true
# systemd's firing coalescing window; 1min is the default, stated so the
# timer's behaviour is readable from its own file
AccuracySec=1min
Unit={service}

[Install]
WantedBy=timers.target
"""


def _sc_verify(cmd: list, what: str) -> tuple:
    env = dict(os.environ)
    env.setdefault("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}")
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True,
                              timeout=60, env=env)
    except (OSError, subprocess.SubprocessError) as e:
        return False, f"{what}: {type(e).__name__}: {e}"
    if proc.returncode != 0:
        err = [str(x) for x in (proc.stderr or "").strip().splitlines()]
        return False, f"{what} exit {proc.returncode}: {' | '.join(err[-2:])[-200:]}"
    return True, ""


def write_job_timer(job: dict, python_exe: str, enable: bool = True) -> dict:
    """Write/replace the unit pair for a job, daemon-reload, and (enable)
    enable+start the timer. Returns a facts dict for the state file:
    what was written, where, calendar, enabled, and any failure words.
    Unit overwrite always happens (a changed schedule replaces the pair)
    — idempotent for unchanged content."""
    name = job["name"]
    if not job_name_ok(name):
        return {"written": False, "error": f"job name {name!r} is not unit-safe"}
    calendar = job.get("schedule", {}).get("calendar", DEFAULT_CALENDAR)
    d = systemd_user_dir()
    base = job_unit_base(name)
    svc = d / f"{base}.service"
    tmr = d / f"{base}.timer"
    # M5.5 (addendum §2): announce BEFORE the write, every path the
    # install touches, and record how the announcement traveled. The
    # zero-cross doctrine applied to the installer itself.
    ann = aide_announce(f"timer install for job '{name}'",
                        timer_install_paths(name))
    d.mkdir(parents=True, exist_ok=True)
    _atomic_write(svc, SERVICE_UNIT.format(
        version=VERSION, name=name, python=python_exe,
        engine=str(Path(__file__).resolve()), job=name))
    _atomic_write(tmr, TIMER_UNIT.format(
        version=VERSION, name=name, calendar=calendar,
        service=f"{base}.service"))
    ok, err = _sc_verify(["systemctl", "--user", "daemon-reload"],
                         "daemon-reload")
    if not ok:
        return {"written": True, "enabled": False, "error": err,
                "calendar": calendar, "units": [str(svc), str(tmr)]}
    if enable:
        # enable --now is idempotent; a changed calendar reaches a running
        # timer through restart
        ok, err = _sc_verify(
            ["systemctl", "--user", "enable", "--now", f"{base}.timer"],
            "enable --now")
        if not ok:
            return {"written": True, "enabled": False, "error": err,
                    "calendar": calendar, "units": [str(svc), str(tmr)]}
        ok, err = _sc_verify(["systemctl", "--user", "restart", f"{base}.timer"],
                             "restart")
    else:
        ok = True
    facts = {"written": True, "enabled": ok, "calendar": calendar,
             "units": [str(svc), str(tmr)],
             "announce": ann["status"],
             "announceCause": ann.get("cause") or ann.get("note") or ""}
    if not ok:
        facts["error"] = err
    return facts


def remove_job_timer(name: str) -> dict:
    """Disable + remove a job's unit pair. Facts for the state file.
    The removal announces too (M5.5): deleting a unit churns exactly the
    same watched paths an install does — the 2026-10-01 00:15 AIDE alert
    was fired by a TEARDOWN, not an install. The announce is printed
    (journald for timer-context runs); removal needs no note lane."""
    if not job_name_ok(name):
        return {"removed": False, "error": f"job name {name!r} is not unit-safe"}
    base = job_unit_base(name)
    print(f"hecate: timer removal for job '{name}': about to remove "
          f"{job_unit_base(name)}.service/.timer and its "
          f"timers.target.wants symlink "
          f"({systemd_user_dir()})")
    _sc_verify(["systemctl", "--user", "disable", "--now", f"{base}.timer"],
               "disable --now")
    d = systemd_user_dir()
    removed = []
    for suffix in (".service", ".timer"):
        p = d / f"{base}{suffix}"
        if p.exists():
            try:
                p.unlink()
                removed.append(str(p))
            except OSError as e:
                return {"removed": False,
                        "error": f"unlink {p}: {type(e).__name__}: {e}"}
    ok, err = _sc_verify(["systemctl", "--user", "daemon-reload"],
                         "daemon-reload")
    # a stopped-but-known unit dies fully on daemon-reload; reset-failed
    # clears any residue so the name cannot arrive "masked" later
    _sc_verify(["systemctl", "--user", "reset-failed", f"{base}.service"],
               "reset-failed")
    facts = {"removed": True, "files": removed}
    if not ok:
        facts["error"] = err
    return facts


def job_name_ok(name: str) -> bool:
    return bool(name) and name not in (".", "..") and all(ch in JOB_NAME_OK for ch in name) and len(name) <= 64


