def snapshot_name() -> str:
    return datetime.now().astimezone().strftime("%Y%m%d-%H%M%S")


def resolve_latest(job_dir: Path):
    """Path of the newest successful snapshot, via the <ts>.latest symlink."""
    if not job_dir.is_dir():
        return None
    best = None
    for e in sorted(job_dir.iterdir()):
        if e.name.endswith(".latest") and e.is_symlink():
            best = e
    if best is None:
        return None
    tgt = os.readlink(best)
    p = Path(tgt) if os.path.isabs(tgt) else best.parent / tgt
    return p if p.is_dir() else None


def remote_latest(host: str, job_dir: str):
    """resolve_latest() over ssh; returns the snapshot NAME (relative,
    which is what remote --link-dest wants) or None."""
    probe = ('d="$1"; l=$(ls -1 "$d" 2>/dev/null | grep "\\.latest$" | tail -1); '
             '[ -n "$l" ] && readlink "$d/$l" && exit 0; exit 1')
    try:
        proc = ssh_script(host, probe, [job_dir], timeout=45)
    except (OSError, subprocess.SubprocessError):
        return None
    name = (proc.stdout or "").strip()
    return name or None


def run_rsync(source: Path, snapshot, link_dest, host: str | None = None):
    """(rc, err-tail, changed). changed = relative paths rsync
    actually wrote this run (itemize receipts). The itemize format is stable from
    rsync 3.1 onward; a parse miss degrades to full-snapshot hashing
    (honest, slower), never to no hashing."""
    cmd = ["rsync", "-a", "--numeric-ids", "--out-format=ITEMIZE %i|%n|"]
    if host is not None:
        cmd += ["-e", RSYNC_E]
    if link_dest is not None:
        cmd.append(f"--link-dest={link_dest}")
    dest_arg = f"{host}:{snapshot}/" if host else f"{snapshot}/"
    cmd += [str(source).rstrip("/") + "/", dest_arg]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True)
    except subprocess.TimeoutExpired:
        return 124, f"rsync timed out: {' '.join(cmd[:4])}...", []
    except OSError as e:
        return 1, f"{type(e).__name__}: {e}", []
    changed = []
    for line in (proc.stdout or "").splitlines():
        if not line.startswith("ITEMIZE "):
            continue
        try:
            flags, name = line[len("ITEMIZE "):].split("|", 1)
        except ValueError:
            continue
        name = name.removesuffix("|").rstrip("/")
        if not name:
            continue
        # %i semantics: flags[0] '>' = this run transferred the item's
        # content; flags[1] 'f' = regular file. Only those need rehashing.
        # '.' = metadata-only, 'h' = hardlinked (same inode as the base,
        # inherited), 'c' = local creation (dir/link chrome), '*' = deletions.
        if len(flags) >= 2 and flags[0] in "<>" and flags[1] == "f":
            changed.append(name)
    tail = (proc.stderr or "").strip().splitlines()
    return (proc.returncode,
            " | ".join([str(x) for x in tail[-3:]])[-400:],
            changed)


def _fail(c: dict, reason: str) -> bool:
    c["override"] = {"status": "failed", "reason": reason}
    c["verified"] = False
    print(f"  corner {c.get('index')}: FAILED — {reason}")
    return False


def _verified_bytes(at, manifest_sha, nfiles, nhashed, ninherited) -> dict:
    return {"at": at, "basis": "snapshot-manifest", "manifest": manifest_sha,
            "files": nfiles, "hashed": nhashed, "inherited": ninherited}


def _local_manifest_for_snapshot(src: Path, snap: Path, changed: list, previous=None) -> tuple:
    """Build this snapshot's manifest from the rsync receipts. Returns
    (verified_obj, note). Inherited files (unchanged, hardlinked by
    rsync's own delta machinery) are trusted from the previous snapshot's
    manifest; changed files are hashed directly. NOT in the previous
    manifest and not written this run (first run after upgrade): hashed
    too — never silently skipped."""
    typed = walk_typed(snap)
    hashed: list = []
    links = sorted(r for r, k in typed.items() if k == "l")
    # prev manifest for inheritance: link-dest bases the new tree on the
    # previous one, so an unchanged file's inode is the same inode the
    # previous manifest hashed. The newest OTHER dir with a manifest is
    # the base (the snapshot rsync linked against).
    parent = snap.parent
    cands = [Path(previous)] if previous is not None else []
    prev = None
    prev_sha_by_rel = {}
    for p in cands:
        m = p / MANIFEST_NAME
        if m.is_file():
            with open(m) as f:
                for line in f:
                    line = line.rstrip("\n")
                    if len(line) >= 67 and line[64:66] == "  ":
                        prev_sha_by_rel[line[66:]] = line[:64]
            prev = p
            break
    changed_set = set(changed)
    n_inherited = 0
    n_hashed = 0
    import hashlib
    for rel, kind in sorted(typed.items()):
        if kind != "f":
            continue
        if rel in changed_set:
            h = hashlib.sha256()
            with open(snap / rel, "rb") as f:
                for b in iter(lambda: f.read(1 << 20), b""):
                    h.update(b)
            hashed.append((rel, h.hexdigest()))
            n_hashed += 1
        elif rel in prev_sha_by_rel and prev is not None and (prev / rel).is_file() and os.path.samefile(snap / rel, prev / rel):
            hashed.append((rel, prev_sha_by_rel[rel]))
            n_inherited += 1
        else:
            # not written this run and not in the previous manifest: the
            # honest path is hashing it (first run after upgrade, or a
            # missing manifest upstream); it is never silently skipped
            h = hashlib.sha256()
            with open(snap / rel, "rb") as f:
                for b in iter(lambda: f.read(1 << 20), b""):
                    h.update(b)
            hashed.append((rel, h.hexdigest()))
            n_hashed += 1
    man_sha = write_manifest(snap, hashed, links)
    v = _verified_bytes(datetime.now().astimezone().isoformat(timespec="seconds"),
                        man_sha, len(hashed), n_hashed, n_inherited)
    return v, (f"hashed {n_hashed}, inherited {n_inherited} from "
               f"{prev.name if prev else 'none'}")


def run_corner(job: dict, c: dict) -> bool:
    name = job["name"]
    transport = c.get("transport", "local")

    if transport not in ("local", "ssh"):
        return _fail(c, f"transport '{transport}' is not implemented in M5 "
                        "(local, ssh; rclone needs its OAuth milestone)")

    observed = destination_observation(c)
    if not observed.get("present"):
        c["override"] = {"status": "unknown", "reason": observed["reason"]}
        print(json.dumps({"corner": c.get("index"), "error": observed["reason"]}), flush=True)
        return False
    if not c.get("identity"):
        c["override"] = {"status": "unknown", "reason": "destination identity not recorded; check and replace the corner before writing"}
        return False

    src = Path(job["source"]["path"]).expanduser()
    host, rpath = None, None
    if transport == "ssh":
        host, rpath = parse_ssh_dest(c["destination"])
        if host is None:
            return _fail(c, f"ssh destination is not host:/path: {c['destination']!r}")
        # never hand rsync a tilde: it is a literal directory inside a path.
        # Resolve the declared destination to its absolute remote path now.
        if rpath.startswith("~"):
            home = resolve_remote_home(host)
            if home is None:
                return _fail(c, f"could not resolve remote home on {host} to expand "
                                f"'~' in {c['destination']}")
            rpath = home + rpath[1:]
    ts = snapshot_name()
    prev = None
    base_prev_name = None

    try:
        if transport == "local":
            job_dir = Path(c["destination"]).expanduser() / "hecate" / name
            job_dir.mkdir(parents=True, exist_ok=True)
            while (job_dir / ts).exists():  # never reuse a timestamp
                time.sleep(1.0)
                ts = snapshot_name()
            snap = job_dir / ts
            prev = resolve_latest(job_dir)          # absolute path
            link = str(prev) if prev else None
            code, err, changed = run_rsync(src, snap, link)
        else:
            assert host is not None and rpath is not None  # bound when transport == "ssh"
            job_dir = f"{rpath.rstrip('/')}/hecate/{name}"
            mk = ssh_script(host, 'mkdir -p "$1"', [job_dir])
            if mk.returncode != 0:
                return _fail(c, f"ssh mkdir {host}:{job_dir} exit {mk.returncode}: "
                                f"{(mk.stderr or '').strip()[-200:]}")
            w = ssh_script(host, 'test -w "$1"', [job_dir])
            if w.returncode != 0:
                return _fail(c, f"remote job dir not writable: {host}:{job_dir}")
            # never reuse a timestamp on the remote side either (M5 loose
            # end: the collision handler now exists on both transports)
            while True:
                coll = ssh_script(host, 'test -e "$1" && echo exists || echo free',
                                  [f"{job_dir}/{ts}"])
                if coll.returncode != 0:
                    return _fail(c, f"collision probe failed on {host}: exit {coll.returncode}")
                if "free" in (coll.stdout or ""):
                    break
                time.sleep(1.0)
                ts = snapshot_name()
            prev_name = remote_latest(host, job_dir)  # relative name
            link = os.path.join("..", prev_name) if prev_name else None
            base_prev_name = prev_name  # captured BEFORE the .latest flip
            snap = f"{job_dir}/{ts}"
            code, err, changed = run_rsync(src, snap, link, host=host)
    except OSError as e:
        return _fail(c, f"{type(e).__name__}: {e}")

    for k in FORBIDDEN_KEYS:  # a v1 leftover must not survive an engine write
        c.pop(k, None)

    if code != 0:
        # honest failure: no success is written that was not observed. The
        # partial snapshot stays on disk but .latest does not move, and
        # lastRun does not advance.
        return _fail(c, f"rsync exit {code}: {err}")

    # ---- M5 Part B: the manifest + the basis (write-time hashing) ----
    print(json.dumps({"corner": c.get("index"), "phase": "manifest"}), flush=True)
    note = ""
    if transport == "local":
        v, note = _local_manifest_for_snapshot(src, snap, changed, previous=prev)
        c["verified"] = v
    else:
        assert host is not None  # bound when transport == "ssh"
        # ssh: the same receipts hold — the bytes are remote, so the engine
        # hashes the SOURCE files that changed (they are the bytes rsync
        # transferred) and ships the full manifest over ssh. An in-flight
        # divergence (file changed mid-run) is caught by the NEXT scrub,
        # which rehashes the destination side. Noted honestly in the basis
        # note. base_prev_name is the link-dest snapshot captured BEFORE
        # the .latest flip (after the flip, remote_latest would return the
        # snapshot just written, which carries no manifest yet).
        rman = ssh_script(host,
                          'd="$1"; test -f "$d/"' + MANIFEST_NAME + ' && cat "$d/"' + MANIFEST_NAME,
                          [f"{job_dir}/{base_prev_name}" if base_prev_name else job_dir],
                          timeout=120)
        prev_sha_by_rel = {}
        prev_name_str = "none"
        if rman.returncode == 0 and rman.stdout:
            for line in rman.stdout.splitlines():
                line = line.rstrip("\n")
                if len(line) >= 67 and line[64:66] == "  ":
                    prev_sha_by_rel[line[66:]] = line[:64]
            prev_name_str = base_prev_name
        changed_set = set(changed)
        hashed, n_hashed, n_inherited = [], 0, 0
        import hashlib
        src_typed = walk_typed(src)
        for rel, kind in sorted(src_typed.items()):
            if kind != "f":
                continue
            if rel in changed_set:
                h = hashlib.sha256()
                with open(src / rel, "rb") as f:
                    for b in iter(lambda: f.read(1 << 20), b""):
                        h.update(b)
                hashed.append((rel, h.hexdigest()))
                n_hashed += 1
            elif rel in prev_sha_by_rel:
                hashed.append((rel, prev_sha_by_rel[rel]))
                n_inherited += 1
            else:
                h = hashlib.sha256()
                with open(src / rel, "rb") as f:
                    for b in iter(lambda: f.read(1 << 20), b""):
                        h.update(b)
                hashed.append((rel, h.hexdigest()))
                n_hashed += 1
        links = sorted(r for r, k in src_typed.items() if k == "l")
        # write the manifest locally (tmp), then cat it over ssh
        tmpdir = state_dir() / "manifest-staging"
        tmpdir.mkdir(parents=True, exist_ok=True)
        tmpman = tmpdir / f"{name}-{ts}.sha"
        lines = [f"{digest}  {rel}" for rel, digest in hashed] + \
                [f"l  {rel}" for rel in links]
        with open(tmpman, "w") as f:
            f.write("\n".join(lines) + ("\n" if lines else ""))
        rc2, err2 = ssh_write_file(host, f"{snap}/{MANIFEST_NAME}", tmpman)
        if rc2 != 0:
            c.pop("override", None)
            c["lastRun"] = datetime.now().astimezone().isoformat(timespec="seconds")
            c["snapshot"] = str(snap)
            c["verified"] = False
            c["override"] = {"status": "unknown",
                             "reason": f"snapshot copied but manifest push failed: {err2}"}
            print(f"  corner {c.get('index')}: snapshot {ts}  MANIFEST PUSH FAILED (unknown)")
            return False
        import hashlib as _hl
        man_sha = _hl.sha256(open(tmpman, "rb").read()).hexdigest()
        tmpman.unlink(missing_ok=True)
        v = _verified_bytes(datetime.now().astimezone().isoformat(timespec="seconds"),
                            man_sha, len(hashed), n_hashed, n_inherited)
        v["basis"] = "source-manifest"
        c["verified"] = v
        note = (f"hashed {n_hashed} (source side of the transfer), inherited "
                f"{n_inherited} from {prev_name_str}")

    c.pop("override", None)
    c.pop("scrub", None)
    c["lastRun"] = datetime.now().astimezone().isoformat(timespec="seconds")
    c["snapshot"] = str(snap)

    # verify by comparing file LISTS, not byte totals. MANIFEST.sha256
    # is snapshot chrome, not content: it exists in every snapshot and
    # never at the source, so it is excluded from both sides
    print(json.dumps({"corner": c.get("index"), "phase": "inventory"}), flush=True)
    src_list = [r for r in file_list(src) if r != MANIFEST_NAME]
    if transport == "local":
        snap_list = [r for r in file_list(snap) if r != MANIFEST_NAME]
    else:
        remote = file_list_ssh(host, snap)
        snap_list = None if remote is None else [r for r in remote if r != MANIFEST_NAME]
    if snap_list is None:
        c["verified"] = False
        c["override"] = {"status": "unknown",
                         "reason": f"snapshot copied but the remote list read failed: {host}:{snap}"}
        print(f"  corner {c.get('index')}: snapshot {ts}  remote list UNREADABLE (unknown)")
        return False
    lists_agree = src_list == snap_list
    if lists_agree:
        c.pop("override", None)
    else:
        missing = sorted(set(src_list) - set(snap_list))[:3]
        extra = sorted(set(snap_list) - set(src_list))[:3]
        c["override"] = {"status": "unknown",
                         "reason": f"list diff after copy: missing={missing} extra={extra}"}
        # the basis stays as written (it is true for the hashed files) but
        # the overall fact is failed
        c["verified"] = False
    if not lists_agree:
        return False

    # success: flip .latest atomically (symlink + rename), exactly one kept
    if transport == "local":
        job_dir_p = Path(job_dir)
        latest = job_dir_p / (ts + ".latest")
        tmp_link = job_dir_p / (ts + ".latest.tmp")
        if tmp_link.is_symlink() or tmp_link.exists():
            tmp_link.unlink()
        os.symlink(ts, tmp_link)
        os.replace(tmp_link, latest)
        for e in job_dir_p.iterdir():
            if e.name.endswith(".latest") and e.name != latest.name:
                e.unlink()
    else:
        assert host is not None  # bound when transport == "ssh"
        flip = ('set -e; d="$1"; t="$2"; ln -s "$t" "$d/$t.latest.tmp" 2>/dev/null; '
                'mv -T "$d/$t.latest.tmp" "$d/$t.latest"; '
                'for l in "$d"/*.latest; do [ "$l" = "$d/$t.latest" ] || rm -f "$l"; done')
        flipped = ssh_script(host, flip, [job_dir, ts])
        if flipped.returncode:
            c["override"] = {"status": "unknown", "reason": f"latest link update exit={flipped.returncode}: {flipped.stderr}"}
            return False

    print(f"  corner {c.get('index')}: snapshot {ts}  src={len(src_list)}f  "
          f"snap={len(snap_list) if snap_list is not None else '?'}f  "
          f"link-dest={'yes' if link else 'first run'}  "
          f"verified={_basis_word(c)}  ({note})")
    return True


def _basis_word(c: dict) -> str:
    v = c.get("verified")
    if isinstance(v, dict):
        return f"yes/{v.get('basis')}"
    if v is True:
        return "yes (legacy list-only)"
    return "no"


def cmd_run(name: str, by_timer: bool = False) -> int:
    state = read_state()
    job, idx = find_job(state, name)
    if job is None:
        print(f"hecate: no such job '{name}' in {state_path()}", file=sys.stderr)
        return 2
    if not job.get("corners"):
        print(f"hecate: job '{name}' declares no corners", file=sys.stderr)
        return 2
    src = Path(job["source"]["path"]).expanduser()
    if not src.is_dir():
        print(f"hecate: source is not a directory: {src}", file=sys.stderr)
        return 2
    if (src / MANIFEST_NAME).exists() or (src / MANIFEST_NAME).is_symlink():
        for c in job["corners"]:
            c["override"] = {"status": "unknown", "reason": f"reserved snapshot manifest path exists in source: {src / MANIFEST_NAME}"}
        state["jobs"][idx] = job
        write_state(state)
        return 4

    lock_fd, lock_err = acquire_run_lock(name)
    if lock_fd is None:
        print(f"hecate: {lock_err}")
        return 0  # not a failure: another run is already doing the work

    try:
        print(f"hecate: run '{name}'  source={src}"
              + ("  [by timer]" if by_timer else ""))
        report = independence_check(job_participants(job))
        blocked = {}
        for finding in report["findings"]:
            if finding["kind"] in ("refuse", "unknown"):
                indexes = [c["index"] for c in job["corners"]] if "source" in finding["corners"] else finding["corners"]
                for index in indexes:
                    blocked[index] = finding["reason"]
        any_failed = False
        for c in job["corners"]:
            # per-corner runs: one corner failing must not stop the others
            print(json.dumps({"corner": c.get("index"), "destination": c.get("destination"), "phase": "copy"}), flush=True)
            try:
                if c["index"] in blocked:
                    c["override"] = {"status": "unknown", "reason": blocked[c["index"]]}
                    any_failed = True
                elif not run_corner(job, c):
                    any_failed = True
            except (OSError, ValueError, subprocess.SubprocessError) as e:
                c["override"] = {"status": "unknown", "reason": f"{type(e).__name__}: {e}"}
                print(json.dumps({"corner": c.get("index"), "error": str(e)}), flush=True)
                any_failed = True
            state["jobs"][idx] = job
            write_state(state)

        try:
            m = measure(src)
            job["source"]["bytes"] = m["bytes"]
            job["source"]["files"] = m["files"]
            job["source"].pop("readError", None)
        except OSError as e:
            job["source"]["readError"] = str(e)
            any_failed = True

        # M5: the run's provenance is a fact (scheduled vs clicked), stored
        # next to lastRun, never a verdict
        job["lastRunMode"] = "timer" if by_timer else "manual"

        # M5 Part A: the schedule ships with the run — a job with a
        # schedule gets its units (re)written every run, so a moved repo or
        # an updated engine path heals on the next night, not never
        if job.get("schedule", {}).get("enabled", False):
            facts = write_job_timer(job, sys.executable or "python3")
            job["timer"] = facts
            if not facts.get("written") or facts.get("error"):
                print(f"  timer: {facts.get('error', 'not written')}")
        else:
            # disabled must be a quiet no-op: no units exist for a job
            # without a schedule, and stale units from a removed schedule
            # are removed here
            if job.get("timer"):
                rfacts = remove_job_timer(name)
                job["timer"] = None
                if not rfacts.get("removed"):
                    print(f"  timer: {rfacts.get('error', 'not removed')}")

        # M5 loose end: destination capacity vs the job it carries. A
        # measured fact per corner, stored as such; the renderer decides
        # what colour it earns.
        for c in job["corners"]:
            cap = destination_capacity(c, name)
            if cap is not None:
                c["capacity"] = cap

        state["jobs"][idx] = job
        write_state(state)
        print(f"hecate: state written {state_path()}")
        return 1 if any_failed else 0
    finally:
        import os as _os
        try:
            _os.close(lock_fd)
        except OSError:
            pass


def corner_capacity_report(src_measure, cap) -> dict:
    """Pair the source's measured size with a corner's measured capacity
    into the honest verdict + numbers (M5.5, addendum §1: pair the
    information with the choice). unknown when either side was
    unreadable — never a silent number and never a fabricated one;
    refuse only on arithmetic (zero free bytes)."""
    if not src_measure or not cap:
        return {"verdict": "unknown",
                "reason": "size or capacity unreadable — no number is shown"}
    src = int(src_measure.get("bytes", 0))
    avail = int(cap.get("availableBytes", 0))
    ratio = round(avail / src, 2) if src > 0 else None
    if avail < src or avail <= 0:
        return {"verdict": "refuse", "ratio": 0,
                "reason": f"sourceBytes={src}, availableBytes={avail}: insufficient capacity for the first copy"}
    if ratio is None:
        return {"verdict": "unknown",
                "reason": "source measured zero bytes; ratio undefined"}
    return {"verdict": "warn" if ratio < 3 else "pass", "ratio": ratio,
            "sourceBytes": src, "availableBytes": avail}


def destination_readiness(c: dict, source_bytes: int) -> dict:
    """Readiness is separate from independence; both gate declarations."""
    ident = corner_identity(c)
    if ident.get("unreadable"):
        return {"verdict": "unknown", "reason": ident["unreadable"]}
    if c.get("transport", "local") == "local":
        p = Path(c["destination"]).expanduser()
        if not p.is_dir() or not os.access(p, os.W_OK | os.X_OK):
            return {"verdict": "refuse", "reason": f"destination not writable: {p}"}
        # The snapshot layout requires hardlinks and symlinks; do not bless FAT/exFAT.
        if ident.get("fstype") in ("vfat", "exfat", "msdos"):
            return {"verdict": "refuse", "reason": f"snapshot hardlinks/symlinks unsupported: fstype={ident['fstype']}"}
    else:
        host, path = parse_ssh_dest(c["destination"])
        if path.startswith("~"):
            home = resolve_remote_home(host)
            if home is None:
                return {"verdict": "unknown", "reason": f"remote home unreadable: {host}"}
            path = home + path[1:]
        try:
            proc = ssh_script(host, 'test -d "$1" && test -w "$1" && command -v rsync >/dev/null && command -v sha256sum >/dev/null', [path])
        except (OSError, subprocess.SubprocessError) as e:
            return {"verdict": "unknown", "reason": str(e)}
        if proc.returncode:
            return {"verdict": "unknown", "reason": f"ssh readiness exit={proc.returncode}: {(proc.stderr or '').strip()[-200:]}"}
    return corner_capacity_report({"bytes": source_bytes}, destination_capacity(c, "wizard-candidate"))


def destination_capacity(c: dict, job_name: str) -> dict | None:
    """Measured capacity facts for a corner's job dir, or None when the
    destination cannot be probed (away/unreadable — never a silent
    number). Facts: bytes available, bytes total, fill fraction, and the
    source's measured size vs available — the under-3x warning data."""
    transport = c.get("transport", "local")
    if transport == "local":
        d = Path(str(c.get("destination", ""))).expanduser() / "hecate" / job_name
        # probe the job dir itself; when it does not exist yet, walk UP to
        # the nearest existing ancestor — the destination root's free space
        # is the honest number for "can this corner hold 3x the source"
        base = d
        while not base.exists() and base != base.parent:
            base = base.parent
        if not base.exists():
            return None
        try:
            stv = os.statvfs(base)
        except OSError:
            return None
        return {"availableBytes": stv.f_bavail * stv.f_frsize,
                "totalBytes": stv.f_blocks * stv.f_frsize}
    if transport == "ssh":
        host, rpath = parse_ssh_dest(str(c.get("destination", "")))
        if host is None:
            return None
        if rpath and rpath.startswith("~"):
            home = resolve_remote_home(host)
            if home is None:
                return None
            rpath = home + rpath[1:]
        # raw df line, parsed on this side (no awk quoting across ssh)
        probe = ('d="$1"; while [ ! -d "$d" ] && [ "$d" != / ]; do d="${d%/*}"; [ -n "$d" ] || d=/; done; '
                 'test -d "$d" || exit 1; '
                 'df -k -P "$d" | tail -1')
        try:
            proc = ssh_script(host, probe,
                              [f"{rpath.rstrip('/')}/hecate/{job_name}"], timeout=45)
        except (OSError, subprocess.SubprocessError):
            return None
        if proc.returncode != 0:
            return None
        parts = (proc.stdout or "").split()
        # fs total used avail use% mount — -P guarantees one line, 6 fields
        if len(parts) < 6:
            return None
        try:
            total, avail = int(parts[1]) * 1024, int(parts[3]) * 1024
        except ValueError:
            return None
        return {"availableBytes": avail, "totalBytes": total}
    return None


def cmd_verify(name: str, scrub: bool = False) -> int:
    """Re-run the list diff against the newest snapshot. No copying.
    With --scrub: re-read the snapshot's bytes and rehash them against
    MANIFEST.sha256 (local read; remote rehash over ssh where the bytes
    are). The length-preserving single-byte flip is what this exists to
    catch — a size change would have failed the list diff already."""
    state = read_state()
    job, idx = find_job(state, name)
    if job is None:
        print(f"hecate: no such job '{name}'", file=sys.stderr)
        return 2
    src = Path(job["source"]["path"]).expanduser()
    any_bad = False
    for c in job["corners"]:
        try:
            observed = destination_observation(c)
            if observed.get("present") is not True:
                c["override"] = {"status": "unknown", "reason": observed["reason"]}
                any_bad = True
                continue
            host = None  # re-bound per corner; a local corner after an ssh
            # corner must never scrub remotely with a stale host
            if c.get("transport") == "ssh":
                host, rpath = parse_ssh_dest(c["destination"])
                if host is None:
                    c["override"] = {"status": "unknown", "reason": f"bad ssh destination: {c['destination']!r}"}
                    any_bad = True
                    continue
                if rpath.startswith("~"):
                    home = resolve_remote_home(host)
                    if home is None:
                        c["override"] = {"status": "unknown",
                                         "reason": f"could not resolve remote home on {host}"}
                        print(f"  corner {c.get('index')}: UNKNOWN — {c['override']['reason']}")
                        any_bad = True
                        continue
                    rpath = home + rpath[1:]
                job_dir = f"{rpath.rstrip('/')}/hecate/{name}"
                prev_name = remote_latest(host, job_dir)
                snap = f"{job_dir}/{prev_name}" if prev_name else None
                if snap is None:
                    c["override"] = {"status": "unknown",
                                     "reason": f"no snapshot found under {host}:{job_dir}"}
                    print(f"  corner {c.get('index')}: UNKNOWN — {c['override']['reason']}")
                    any_bad = True
                    continue
                remote = file_list_ssh(host, snap)
                snap_list = None if remote is None else [r for r in remote if r != MANIFEST_NAME]
            else:
                job_dir = Path(c["destination"]).expanduser() / "hecate" / name
                snap = resolve_latest(job_dir)
                if snap is None:
                    c["override"] = {"status": "unknown",
                                     "reason": f"no snapshot found under {job_dir}"}
                    print(f"  corner {c.get('index')}: UNKNOWN — {c['override']['reason']}")
                    any_bad = True
                    continue
                snap_list = [r for r in file_list(snap) if r != MANIFEST_NAME]
            if snap_list is None:
                c["verified"] = False
                c["override"] = {"status": "unknown",
                                 "reason": f"remote list read failed: {snap}"}
                print(f"  corner {c.get('index')}: UNKNOWN — {c['override']['reason']}")
                any_bad = True
                continue
            same = [r for r in file_list(src) if r != MANIFEST_NAME] == snap_list
            # M5 contract: `verified` is the RUN's basis object — this pass
            # never overwrites it. The list-diff result is a fact of THIS
            # check; on agreement the run's basis stands (an old boolean-era
            # true stays true), on disagreement the override says so.
            c["sourceComparison"] = {"at": _now_iso(), "snapshot": str(snap), "pathsAgree": same}
            # A live source may have legitimately changed since the snapshot.
            # Its path comparison never clears a copy/scrub failure or brands history corrupt.
            print(json.dumps({"corner": c.get("index"), "sourcePathsAgree": same, "snapshot": str(snap)}), flush=True)
            if scrub:
                try:
                    any_bad = (scrub_corner(c, snap, host) or any_bad)
                except (OSError, ValueError, subprocess.SubprocessError) as e:
                    c["override"] = {"status": "unknown", "reason": f"scrub read failed: {e}"}
                    c["scrub"] = {"at": _now_iso(), "snapshot": str(snap), "ok": False, "reason": str(e)}
                    any_bad = True
        except (OSError, ValueError, subprocess.SubprocessError) as e:
            c["override"] = {"status": "unknown", "reason": f"{type(e).__name__}: {e}"}
            print(json.dumps({"corner": c.get("index"), "error": str(e)}), flush=True)
            any_bad = True
        finally:
            state["jobs"][idx] = job
            write_state(state)
    state["jobs"][idx] = job
    write_state(state)
    return 1 if any_bad else 0


def scrub_corner(c: dict, snap, host) -> bool:
    """The byte-level scrub of one corner's newest snapshot. Writes the
    measured fact into the corner (scrub: {at, ok, files, bad...}) and
    returns True when the scrub found a problem."""
    if host is not None:
        try:
            proc = ssh_script(host, REMOTE_SCRUB, [str(snap)], timeout=1800)
        except (OSError, subprocess.SubprocessError) as e:
            c["scrub"] = {"at": _now_iso(), "ok": False,
                          "snapshot": str(snap),
                          "reason": f"ssh scrub failed: {type(e).__name__}: {e}"}
            c["override"] = {"status": "unknown", "reason": c["scrub"]["reason"]}
            print(f"  corner {c.get('index')}: SCRUB UNKNOWN — {c['scrub']['reason']}")
            return True
        if proc.returncode == 3 and "ERR" in (proc.stdout or ""):
            reason = (proc.stdout or "").strip().splitlines()[-1][:200]
            c["scrub"] = {"at": _now_iso(), "snapshot": str(snap), "ok": False, "reason": reason}
            c["override"] = {"status": "unknown", "reason": reason}
            print(f"  corner {c.get('index')}: SCRUB UNKNOWN — {reason}")
            return True
        mismatches = [ln for ln in (proc.stdout or "").splitlines()
                      if ln.startswith("MISMATCH ")]
        summary = next((ln for ln in (proc.stdout or "").splitlines()
                        if ln.startswith("SCRUB ")), "")
        ok = proc.returncode == 0 and not mismatches
        c["scrub"] = {"at": _now_iso(), "ok": ok,
                      "snapshot": str(snap),
                      "summary": summary,
                      "mismatches": [m[:300] for m in mismatches[:10]]}
        if not ok:
            c["override"] = {"status": "unknown",
                             "reason": f"scrub mismatch in {snap}: "
                                       f"{mismatches[0][:150] if mismatches else (proc.stderr or '').strip()[-150:]}"}
        print(f"  corner {c.get('index')}: SCRUB {'OK' if ok else 'FAILED'}"
              + (f"  {summary}" if summary else ""))
        return not ok
    res = scrub_check_manifest(Path(snap))
    c["scrub"] = {"at": _now_iso(), "ok": bool(res.get("ok")),
                  "snapshot": str(snap),
                  "files": res.get("files"), "checked": res.get("checked")}
    if not res.get("ok"):
        c["scrub"]["reason"] = res.get("reason") or (
            f"bad={[(b[0], b[1][:8], str(b[2])[:8]) for b in res.get('bad', [])[:3]]} "
            f"missing={res.get('missing', [])[:3]} extra={res.get('extra', [])[:3]}")
        c["override"] = {"status": "unknown",
                         "reason": f"scrub mismatch in {snap}: {c['scrub']['reason'][:180]}"}
    print(f"  corner {c.get('index')}: SCRUB {'OK' if res.get('ok') else 'FAILED'}"
          f"  files={res.get('files')} checked={res.get('checked')}"
          + ("" if res.get("ok") else f"  {c['scrub']['reason'][:150]}"))
    return not res.get("ok", False)


def _now_iso() -> str:
    return datetime.now().astimezone().isoformat(timespec="seconds")


def cmd_classify(name: str | None) -> int:
    state = read_state()
    now = datetime.now().astimezone()
    print(f"classified at {now.isoformat(timespec='seconds')}")
    rc = 0
    v1 = isinstance(state.get("version"), int) and state["version"] < 2
    if v1 and state.get("jobs"):
        print("  (v1 state file: stored verdicts are not re-derivable — all corners unknown; run the engine to migrate)")
    for job in state.get("jobs", []):
        if name and job.get("name") != name:
            continue
        for c in job.get("corners", []):
            if v1:
                word, reason = "unknown", "v1 state shape (stored status/ageDays) — not current knowledge"
            else:
                word, reason = classify_corner(c, now)
            print(f"  {job.get('name')} corner {c.get('index')} "
                  f"[{c.get('transport')}] -> {word}  ({reason})")
    return rc


def cmd_check(name: str, as_json: bool = False) -> int:
    state = read_state()
    job, _ = find_job(state, name)
    if job is None:
        print(f"hecate: no such job '{name}'", file=sys.stderr)
        return 2
    report = independence_check(job_participants(job))
    if as_json:
        print(json.dumps(report, indent=2))
    else:
        print_report(report, f"job '{name}' (source + {len(job.get('corners', []))} corners)")
    return VERDICT_EXIT[report["verdict"]]


def cmd_check_fixtures(path: str, as_json: bool = False) -> int:
    """The same independence_check() on declared fixture device data — more
    honest than needing two physical drives to exist (M3 brief)."""
    try:
        with open(path) as f:
            fx = json.load(f)
    except (OSError, json.JSONDecodeError) as e:
        print(f"hecate: fixture unreadable: {e}", file=sys.stderr)
        return 2
    parts = fx.get("participants")
    if not isinstance(parts, list) or not parts:
        print(f"hecate: fixture {path} has no participants list", file=sys.stderr)
        return 2
    report = independence_check(parts)
    if as_json:
        print(json.dumps(report, indent=2))
    else:
        print_report(report, f"fixture '{fx.get('name', path)}' ({len(parts)} participants)")
    return VERDICT_EXIT[report["verdict"]]


def _gate_corner(state: dict, job: dict, cand: dict, accept_warning: bool) -> int:
    """Law 1 at declaration time: refuse what the check refuses, record the
    acceptance of what it warns about. Returns 0 when the corner landed."""
    report = independence_check(job_participants(job, extra_corner=cand))
    ready = destination_readiness(cand, job["source"]["bytes"])
    if ready["verdict"] in ("refuse", "unknown"):
        report["findings"].append({"kind": ready["verdict"], "corners": [cand["index"]],
                                   "reason": ready["reason"], "evidence": ready})
        if report["verdict"] != "refuse":
            report["verdict"] = ready["verdict"]
    print_report(report, f"candidate corner {cand['index']} -> {cand['destination']} "
                         f"for job '{job['name']}'")
    verdict = report["verdict"]
    if verdict == "refuse":
        print("hecate: corner NOT added — a corner is a destination that fails independently "
              "(PLAN law 1). Choose a different destination.", file=sys.stderr)
        return 3
    if verdict == "unknown":
        print("hecate: corner NOT added — device identity could not be read, and unreadable "
              "is not independent. Fix the destination or the connection.", file=sys.stderr)
        return 4
    if verdict == "warn":
        warns = [f for f in report["findings"] if f["kind"] == "warn"]
        if not accept_warning:
            print("hecate: corner NOT added — the check warns. Continue deliberately with "
                  "--accept-warning; the acceptance is recorded in the state file.",
                  file=sys.stderr)
            return 5
        cand["independenceAck"] = {
            "at": datetime.now().astimezone().isoformat(timespec="seconds"),
            "summary": " | ".join(w["reason"] for w in warns),
        }
    cand["identity"] = corner_identity(cand)
    return 0


def cmd_add_job(name: str, source: str, dest: str, horizon: int,
                transport: str = "local", accept_warning: bool = False) -> int:
    state = read_state()
    if not job_name_ok(name):
        print(f"hecate: job name {name!r} is not allowed: use letters, digits, "
              f"'.', '_' or '-' (it becomes a systemd unit name)", file=sys.stderr)
        return 2
    if find_job(state, name)[0] is not None:
        print(f"hecate: job '{name}' already exists", file=sys.stderr)
        return 2
    if transport not in ("local", "ssh") or horizon <= 0:
        print(json.dumps({"error": "unsupported transport or nonpositive horizon"}))
        return 2
    src = Path(source).expanduser().resolve()
    dst = str(Path(dest).expanduser().resolve()) if transport == "local" else dest
    if not src.is_dir():
        print(f"hecate: source is not a directory: {src}", file=sys.stderr)
        return 2
    m = measure(src)
    job = {
        "name": name,
        "source": {"path": str(src), "bytes": m["bytes"], "files": m["files"]},
        "corners": [],
    }
    cand = {"index": 1, "transport": transport, "destination": str(dst),
            "horizonHours": horizon}
    rc = _gate_corner(state, job, cand, accept_warning=accept_warning)
    if rc != 0:
        return rc
    job["corners"].append(cand)
    # M5 Part A: a declared job carries its schedule from day one —
    # nightly 02:00 by default, disabled until the wizard (or the user)
    # arms it. Units are written at schedule-set/run time, not here: an
    # unconfigured job stays a quiet no-op with zero units on disk.
    job["schedule"] = {"enabled": False, "calendar": DEFAULT_CALENDAR}
    state["jobs"].append(job)
    write_state(state)
