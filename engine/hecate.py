def independence_check(participants: list) -> dict:
    """Structured independence report for [source] + corners.

    participants: [{"index": int|str, "transport": str, "identity": dict}, ...]
    identity comes from read_local_identity / read_ssh_identity / fixtures
    (fixtures may add "model", "serial", "power" for the sibling lanes).

    Returns {"verdict": pass|warn|refuse|unknown, "findings": [...]}; every
    finding carries its kind, the corners it names, the reason, and the
    EVIDENCE it used. Never a boolean; never a silent pass.
    """
    findings = []

    usable = []   # participants with a readable filesystem identity
    for p in participants:
        ident = p.get("identity") or {}
        if "unreadable" in ident:
            findings.append({
                "kind": "unknown", "corners": [p["index"]],
                "reason": f"device identity could not be read — not a pass: {ident['unreadable']}",
                "evidence": ident["unreadable"],
            })
        elif "cloud" in ident:
            findings.append({
                "kind": "cloud", "corners": [p["index"]],
                "reason": ident["cloud"],
                "evidence": "no filesystem identity exists for a cloud remote",
            })
            findings.append({"kind": "warn", "corners": [p["index"]],
                             "reason": ident["cloud"], "evidence": "cloud failure domain is declared, not measured"})
        else:
            usable.append(p)

    cloud_corners = [p for p in participants if p.get("index") != "source" and "cloud" in (p.get("identity") or {})]
    if len(cloud_corners) >= MAX_CORNERS:
        findings.append({"kind": "refuse", "corners": [p["index"] for p in cloud_corners],
                         "reason": "all three corners share cloud account, billing, or provider failure risks",
                         "evidence": "three cloud destinations; no non-cloud corner"})
    # hard refusal: same filesystem, pairwise (corners) and vs the source
    src = next((p for p in usable if p["index"] == "source"), None)
    corners = [p for p in usable if p["index"] != "source"]
    for i in range(len(corners)):
        for j in range(i + 1, len(corners)):
            a, b = corners[i], corners[j]
            same, ev = same_filesystem(a["identity"], b["identity"])
            if same:
                findings.append({
                    "kind": "refuse", "corners": [a["index"], b["index"]],
                    "reason": (f"corners {a['index']} and {b['index']} resolve to the same "
                               f"filesystem ({ev}). If that disk fails, both copies are lost at "
                               "the same moment and you will not have a backup."),
                    "evidence": ev,
                })
    if src is not None:
        for c in corners:
            same, ev = same_filesystem(src["identity"], c["identity"])
            if same:
                findings.append({
                    "kind": "refuse", "corners": [c["index"]], "source": True,
                    "reason": (f"corner {c['index']} resolves to the same filesystem as the "
                               f"source ({ev}). This copy lives on the disk it is supposed to "
                               "be protecting."),
                    "evidence": ev,
                })

    # overridable warning: correlated failure that is judgement, not arithmetic
    warned_pairs = set()
    for i in range(len(corners)):
        for j in range(i + 1, len(corners)):
            a, b = corners[i], corners[j]
            if a["transport"] == "ssh" and b["transport"] == "ssh":
                pa, pb = power_group(a["identity"], "ssh"), power_group(b["identity"], "ssh")
                if pa and pa == pb:
                    findings.append({
                        "kind": "warn", "corners": [a["index"], b["index"]],
                        "reason": (f"corners {a['index']} and {b['index']} both live on one "
                                   f"machine ({a['identity'].get('host')}): its power, its "
                                   "updates and its hardware are shared. Continue if you know "
                                   "why they are separate."),
                        "evidence": f"same power path: {pa}",
                    })
                    warned_pairs.add((a["index"], b["index"]))
    for i in range(len(corners)):
        for j in range(i + 1, len(corners)):
            a, b = corners[i], corners[j]
            if (a["index"], b["index"]) in warned_pairs:
                continue
            ma, mb = model_of(a["identity"]), model_of(b["identity"])
            pa = power_group(a["identity"], a["transport"])
            pb = power_group(b["identity"], b["transport"])
            if ma and mb and ma == mb and pa and pa == pb:
                sa, sb = a["identity"].get("serial"), b["identity"].get("serial")
                pa = a["identity"].get("power") or power_group(a["identity"], "local")
                pb = b["identity"].get("power") or power_group(b["identity"], "local")
                if pa and pa == pb:
                    findings.append({
                        "kind": "warn", "corners": [a["index"], b["index"]],
                        "reason": (f"corners {a['index']} and {b['index']} look like siblings: "
                                   f"same model ({ma}), same power path. "
                                   "Same age and use profile means correlated failure. "
                                   "Continue if you know why they are separate."),
                        "evidence": f"model={ma} serials={sa!r}/{sb!r} power={pa}",
                    })
            elif ma and mb and ma == mb:
                findings.append({"kind": "warn", "corners": [a["index"], b["index"]],
                                 "reason": f"same model family ({ma}); correlated hardware failure remains possible",
                                 "evidence": f"model={ma}"})
            if pa and pa == pb and not (ma and mb and ma == mb):
                findings.append({"kind": "warn", "corners": [a["index"], b["index"]],
                                 "reason": "corners share a power path; a power failure can affect both",
                                 "evidence": f"same power path: {pa}"})

    verdict = "pass"
    kinds = {f["kind"] for f in findings}
    if "refuse" in kinds:
        verdict = "refuse"
    elif "unknown" in kinds:
        verdict = "unknown"
    elif "warn" in kinds:
        verdict = "warn"
    return {"verdict": verdict, "findings": findings}


