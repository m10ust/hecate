# --- the AIDE announce (addendum §2) --------------------------------------
#
# Zero-cross doctrine applied to the installer: before the engine writes
# ANY user unit, it announces every path it is about to touch. Where the
# box runs AIDE, the announcement goes to aide-note naming every path
# verbatim and absolute (the adjudicator greps literally); where AIDE is
# absent, the engine says so and continues. Never a silent service.
#
# THE TRAP (receipted live 2026-10-01): unprivileged aide-note LIES —
# rc 0 and 'noted @ ...' on stdout while stderr carries 'Permission
# denied' and nothing lands (/var/lib/aide/notes is root-700). The exit
# code cannot be trusted; the ONLY trustworthy signals are the
# writability probe before and the note read-back after. When the lane
# cannot be used, the announcement degrades to the journald receipt
# trail (the timer's own lane) + the state file, and says which of the
# two happened — never a silent pass and never a claimed note that
# does not exist.

AIDE_NOTE = "/usr/local/sbin/aide-note"
AIDE_NOTES_DIR = Path("/var/lib/aide/notes")


def timer_install_paths(name: str) -> list:
    """Every absolute path a timer install writes, verbatim — the unit
    pair plus the enable symlinks under timers.target.wants and the
    directory rows around them. aide-check greps literally, so a note
    naming only some paths adjudicates nothing."""
    d = systemd_user_dir()
    base = job_unit_base(name)
    units = [str(d / f"{base}.service"), str(d / f"{base}.timer")]
    wants = d / "timers.target.wants"
    parents = []
    parent = d
    while not parent.exists():
        parents.append(str(parent))
        parent = parent.parent
    return parents + units + [p + ".tmp" for p in units] + [str(wants), str(wants / f"{base}.timer")]


def aide_announce(what: str, paths: list, runner: str = AIDE_NOTE,
                  notes_dir: Path = AIDE_NOTES_DIR) -> dict:
    """Announce `paths` for `what`. Tries aide-note when AIDE is present;
    trusts neither its exit code nor its stdout — verifies the note
    landed by reading the notes dir back. Returns one of:
      {"status": "absent",  "message": ...}   — no AIDE on this box
      {"status": "noted",   "note": <file>}   — verified by read-back
      {"status": "degraded","cause","message"}— lane unusable; the full
        announcement (every path verbatim) rides stdout+journald+state
    The degraded message is the announcement itself: whoever reads the
    journal or the state file sees exactly what the installer touched,
    so the honest fallback is also the useful one."""
    message = (f"hecate: {what}: about to write {len(paths)} path(s): "
               + " ".join(paths))
    print(message, flush=True)
    if not Path(AIDE_NOTE).exists() and runner == AIDE_NOTE:
        return {"status": "absent",
                "message": "AIDE not present on this box; announcement "
                           "rides the engine's own output (journald for "
                           "timer runs, the state file for the record)"}
    before = set()
    try:
        before = {p.name for p in notes_dir.iterdir()}
    except OSError:
        before = None  # unreadable now; try anyway, read-back decides
    try:
        proc = subprocess.run([runner, message], capture_output=True,
                              text=True, timeout=30)
    except (OSError, subprocess.SubprocessError) as e:
        return {"status": "degraded",
                "cause": f"aide-note did not run: {type(e).__name__}: {e}"[:200],
                "message": message}
    try:
        after = {p.name for p in notes_dir.iterdir()}
    except OSError:
        after = None
    landed = None
    if after is not None:
        new = after - (before or set())
        # the read-back: a new note file whose content names our paths
        for nfn in sorted(new):
            try:
                txt = (notes_dir / nfn).read_text(errors="replace")
            except OSError:
                continue
            if all(str(p) in txt for p in paths):
                landed = str(notes_dir / nfn)
                break
    if landed:
        return {"status": "noted", "note": landed, "message": message}
    # aide-note said fine and nothing verifiable landed — the unprivileged
    # lie, or a notes dir we cannot read. Either way: say it, record it.
    err = (proc.stderr or "").strip().splitlines()
    cause = (err[-1] if err else
             f"aide-note exited {proc.returncode} but the note could not be "
             f"verified by read-back (notes dir unreadable or unchanged)")
    return {"status": "degraded", "cause": cause[:200], "message": message}


# --- the backed-disk identity key (addendum §3, the bee) -------------------
#
# The bee has one btrfs root: / is /dev/mapper/root[/@] (st_dev 32) and
# /home is /dev/mapper/root[/@home] (st_dev 30) — one disk, one UUID,
# TWO st_dev values, because every btrfs subvolume gets its own
# anonymous device id. st_dev equality would pass both as independent;
# the UUID check catches this pair today, but a filesystem whose UUID
# cannot be read must not slip through on st_dev inequality. The key is
# the cleaned backing source: strip the [/subvol] suffix and everything
# that varies within one disk collapses to one key.

def backed_disk_key(ident: dict):
    """A key that is equal iff two identities ride the same backing
    disk, or None when nothing disk-shaped is readable. UUID first (the
    strong, portable id), then the mount source with any btrfs subvolume
    suffix stripped. Never a fabricated key: no disk evidence, no key."""
    uuid = ident.get("fsuuid")
    if uuid:
        return f"uuid:{uuid}"
    src = ident.get("fssource")
    if src and str(src).startswith("/dev/"):
        return "src:" + str(src).split("[", 1)[0]
    return None


DEFAULT_CALENDAR = "*-*-* 02:00:00"



def classify_corner(c: dict, now: datetime | None = None) -> tuple:
    """Return (word, reason). Five words: current away stale failed unknown."""
    now = now or datetime.now().astimezone()
    observed = destination_observation(c)
    if observed.get("present") is not True:
        lr = c.get("lastRun")
        try:
            then = datetime.fromisoformat(str(lr))
            age = f"age {(now - then).total_seconds() / 3600:.1f}h" if then.tzinfo else "lastRun has no timezone"
        except (ValueError, TypeError):
            age = "never run" if not lr else "unparseable lastRun"
        return ("away" if observed.get("present") is False else "unknown"), observed["reason"] + " · " + age
    ov = c.get("override") or {}
    if isinstance(ov, dict) and ov.get("status") in ("failed", "unknown"):
        return ov.get("status"), str(ov.get("reason", ""))
    # A stored v1 "status" is NEVER trusted — a verdict the file cannot
    # re-derive (P1). Old-shape files classify wholesale as unknown via the
    # version gate in cmd_classify; there is no per-corner v1 honouring.
    dest = c.get("destination", "")
    lr = c.get("lastRun")
    if not lr:
        return "unknown", "never run"
    # away needs a KNOWN last run (PLAN: "expected absence with a known
    # last run"); never-run + absent destination is unknown, not away
    if c.get("transport") == "local" and dest and not Path(dest).expanduser().is_dir():
        return "away", f"destination not present: {dest}"
    try:
        then = datetime.fromisoformat(str(lr))
    except ValueError:
        return "unknown", f"unparseable lastRun: {lr}"
    if then.tzinfo is None:
        return "unknown", "lastRun has no timezone"
    age_h = (now - then).total_seconds() / 3600.0
    horizon = c.get("horizonHours", DEFAULT_HORIZON_HOURS)
    if age_h <= horizon:
        return "current", f"age {age_h:.1f}h within {horizon}h horizon"
    return "stale", f"age {age_h:.1f}h past {horizon}h horizon"


