#!/usr/bin/env python3
"""Hecate engine — M5.5 (v0.0.6: picker, AIDE announce, backed-disk key).

The thing that makes actual copies and writes facts. Contract: PLAN.md
"Data contract (corrected 2026-09-30)". This engine NEVER stores a `status`
or `ageDays` for anything the clock can decide; the only stored verdict is
an `override` for `failed`/`unknown`, carrying the failure's own words.

M5 Part A — systemd user timers, one pair per job, generated by the engine
(`~/.config/systemd/user/hecate-<job>.{service,timer}`), no sudo anywhere.
`Persistent=true` so a window missed to sleep fires on wake. The engine,
not the timer, writes `lastRun` — a timer that fired without a recorded
run is impossible because the timer IS an engine run (`--by-timer`). A
file lock makes overlapping runs (timer + click) wait-free impossible:
the second run exits quietly instead of interleaving snapshots.

M5 Part B — verification stores a BASIS, never a verdict:
`verified: {at, basis, manifest, files, hashed, inherited}` where basis is
one of `bytes` (hashed what this run wrote + inherited the rest via
rsync's own hardlink receipts), `provider-checksum` (cloud, later), or
`size+mtime`. `MANIFEST.sha256` lives INSIDE the snapshot (sha256sum -c
compatible: the receipt travels with the data). `verify` re-reads the
destination bytes and rehashes (the scrub); flipping one byte without
changing the length — the case list verification cannot catch — fails it.

Law 1 (PLAN, the product): corners must be provably independent. The
independence check is a first-class engine function that returns structured
results — pass / warn / refuse / unknown, each with the reason and the
EVIDENCE it used (st_dev or filesystem UUID) — never a boolean, and never
a silent pass when identity could not be read. Refuse is arithmetic (same
filesystem); warn is judgement (model family, shared power path, two
corners on one machine); cloud corners are declare-and-warn by nature (L1).

Subcommands:
  run <job> [--by-timer]        run the job's corners now (per-corner results;
                                one corner failing never stops the others).
                                --by-timer marks lastRun provenance: this run
                                was scheduled, not clicked (fact, not verdict)
  verify <job> [--scrub]        re-run the file-list diff without copying;
                                --scrub re-reads the snapshot bytes and
                                rehashes them against MANIFEST.sha256 (the
                                destination-side rot check)
  timers                        list timer state the engine tracks
  classify [job]                print the display-time classification per corner
  check <job>                   independence check, on demand (structured)
  check-fixtures <file.json>    the same check on fixture device data
  add-job <name> <src> <dest>    declare a job + corner 1 (local transport;
                                the check runs at declaration)
  add-corner <job> <dest> [--transport local|ssh] [--horizon H]
                                [--accept-warning]
                                declare corner 2 or 3; REFUSED when the check
                                refuses, WARNs need --accept-warning (recorded)
  rm-job <name>                 remove a job declaration (keeps snapshots,
                                removes its timer units)
  state                         print the state file
  pick-folder [source|dest]     run the desktop folder chooser (the
                                Omarchy portal picker; prints JSON:
                                picked / nothing-picked / fault)

State:  ~/.local/state/hecate/state.json (engine-owned, one writer)
Layout: <dest>/hecate/<job>/<YYYYMMDD-HHMMSS>/ + <timestamp>.latest symlink
        linking to the newest successful snapshot. Hardlinks via
        --link-dest: unchanged files cost one inode, and a file deleted at
        the source survives in yesterday's tree. ssh corners run the same
        rsync over ssh (link-dest relative to the remote snapshot dir).
"""
