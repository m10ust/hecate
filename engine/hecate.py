# The desktop chooser already ships on every Omarchy box; building a
# second one would be a second thing to trust. Absolute first (stranger
# boxes carry the same /usr/share layout), PATH fallback for unusual
# installs. Omarchy's implementation is a long-lived Python process
# BECAUSE the portal answers with a directed Response signal — a client
# that exits before the answer never hears it — and it times out after
# 600s. Both traps are the brief's; we inherit them rather than rebuild
# them.
OMARCHY_FILE_SELECT = "/usr/share/omarchy/bin/omarchy-file-select"
PICKER_TITLE_SOURCE = "Which folder do you want backed up?"
PICKER_TITLE_DEST = "Where should the copies live?"


def picker_command() -> list:
    """[argv...] for the directory chooser, absolute with PATH fallback."""
    p = Path(OMARCHY_FILE_SELECT)
    if p.is_file() and os.access(p, os.X_OK):
        return [str(p)]
    from shutil import which
    found = which("omarchy-file-select")
    if found:
        return [found]
    return [str(p)]  # absent too: run reports the fault, never a guess


def picker_result(rc: int, out: str, err: str) -> dict:
    """The chooser's exit contract, not flattened. exit 0 = a path came
    back (stdout is local paths, one per line — the portal URIs are
    converted by omarchy itself); exit 1 = the user picked nothing —
    a decision, not an error, and the wizard stays on its screen;
    exit 2 = the chooser never ran — a fault, surfaced with its own
    words so the typed-path fallback can say which happened. Exit 0
    with anything but exactly one absolute path is a fault too: never
    a silent empty pick."""
    if rc == 0:
        lines = [ln.strip() for ln in (out or "").splitlines() if ln.strip()]
        if len(lines) == 1 and lines[0].startswith("/"):
            return {"outcome": "picked", "path": lines[0]}
        why = (f"chooser exited 0 with unexpected stdout "
               f"({len(lines)} lines): {out!r}"[:200])
        return {"outcome": "fault", "error": why}
    if rc == 1:
        return {"outcome": "nothing-picked"}
    why = (err or "").strip().splitlines()
    return {"outcome": "fault",
            "error": (why[-1] if why else f"chooser exited {rc}")[:200]}


