def cmd_replace_corner(name: str, corner: str, dest: str, transport: str,
                       horizon: int | None, accept_warning: bool) -> int:
    """Re-entry: point an existing corner at a new destination. The old
    corner's run facts (lastRun, snapshot, verified) do not travel — a
    new destination has no history until it runs. The full independence
    check runs with the OLD corners swapped out for the candidate."""
    state = read_state()
    if transport not in ("local", "ssh") or (horizon is not None and horizon <= 0):
        print(json.dumps({"error": "unsupported transport or nonpositive horizon"}))
        return 2
    job, idx = find_job(state, name)
    if job is None:
        print(f"hecate: no such job '{name}'", file=sys.stderr)
        return 2
    try:
        cidx = int(corner)
    except ValueError:
        print(f"hecate: corner index must be an integer (1-3): {corner!r}", file=sys.stderr)
        return 2
    corners = job.get("corners", [])
    old = next((c for c in corners if int(c.get("index", 0)) == cidx), None)
    if old is None:
        print(f"hecate: job '{name}' has no corner {cidx}", file=sys.stderr)
        return 2
    dst = str(Path(dest).expanduser().resolve()) if transport == "local" else dest
    cand = {"index": cidx, "transport": transport, "destination": dst,
            "horizonHours": horizon if horizon is not None
            else int(old.get("horizonHours", DEFAULT_HORIZON_HOURS))}
    # check with the candidate IN PLACE of the old corner (the old
    # destination is leaving; it must not veto its replacement)
    trial = [c for c in corners if int(c.get("index", 0)) != cidx] + [cand]
    trial_job = {"name": job["name"], "source": job["source"], "corners": trial}
    report = independence_check(job_participants(trial_job))
    ready = destination_readiness(cand, job["source"]["bytes"])
    if ready["verdict"] in ("refuse", "unknown"):
        report["findings"].append({"kind": ready["verdict"], "corners": [cidx],
                                   "reason": ready["reason"], "evidence": ready})
        if report["verdict"] != "refuse":
            report["verdict"] = ready["verdict"]
    print_report(report, f"corner {cidx} of '{name}' -> {dst}")
    verdict = report["verdict"]
    if verdict == "refuse":
        print("hecate: corner NOT replaced — same filesystem as another participant "
              "(law 1). Choose a different destination.", file=sys.stderr)
        return 3
    if verdict == "unknown":
        print("hecate: corner NOT replaced — device identity unreadable; unreadable "
              "is not independent.", file=sys.stderr)
        return 4
    if verdict == "warn":
        if not accept_warning:
            print("hecate: corner NOT replaced — the check warns. Continue deliberately "
                  "with --accept-warning; the acceptance is recorded.", file=sys.stderr)
            return 5
        warns = [f for f in report["findings"] if f["kind"] == "warn"]
        cand["independenceAck"] = {
            "at": datetime.now().astimezone().isoformat(timespec="seconds"),
            "summary": " | ".join(w["reason"] for w in warns),
        }
    cand["identity"] = corner_identity(cand)
    corners[corners.index(old)] = cand
    state["jobs"][idx] = job
    write_state(state)
    print(f"hecate: corner {cidx} of '{name}' replaced  {transport} -> {dst} "
          f"(previous history does not travel; run to seed)")
    return 0


