def state_dir() -> Path:
    xdg = os.environ.get("XDG_STATE_HOME") or os.path.expanduser("~/.local/state")
    return Path(xdg) / "hecate"


def state_path() -> Path:
    return state_dir() / "state.json"


def empty_state() -> dict:
    return {"version": 2, "writtenBy": f"hecate v{VERSION}", "jobs": []}


def read_state() -> dict:
    p = state_path()
    if not p.exists():
        return empty_state()
    try:
        with open(p) as f:
            s = json.load(f)
    except (json.JSONDecodeError, OSError) as e:
        raise SystemExit(f"hecate: state file is unreadable ({e}) — fix or delete {p}; "
                         "the engine refuses to guess")
    if not isinstance(s, dict) or not isinstance(s.get("jobs", []), list):
        raise SystemExit(f"hecate: state file is not a hecate state: {p}")
    return s


def write_state(state: dict) -> None:
    state["version"] = 2
    state["writtenBy"] = f"hecate v{VERSION}"
    p = state_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_name(p.name + ".tmp")
    with open(tmp, "w") as f:
        json.dump(state, f, indent=2)
        f.write("\n")
    os.replace(tmp, p)  # atomic: the QML FileView watcher sees one change


def find_job(state: dict, name: str):
    for i, j in enumerate(state.get("jobs", [])):
        if isinstance(j, dict) and j.get("name") == name:
            return j, i
    return None, -1


