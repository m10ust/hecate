def cmd_measure_source(path: str) -> int:
    """The wizard's first screen: real size and file count of a source,
    by the engine's own measure(). Read-only. JSON on stdout."""
    p = Path(path).expanduser()
    if not p.is_dir():
        print(json.dumps({"error": f"not a directory: {p}"}))
        return 2
    if (p / MANIFEST_NAME).exists():
        print(json.dumps({"error": f"reserved snapshot manifest path exists in source: {p / MANIFEST_NAME}"}))
        return 2
    try:
        m = measure(p)
    except OSError as e:
        print(json.dumps({"error": f"source read failed: {e}"}))
        return 4
    print(json.dumps({"path": str(p), "bytes": m["bytes"], "files": m["files"]}))
    return 0


def cmd_check_destination(source: str, dest: str, transport: str,
                          job_name: str | None = None,
                          also_parts: list | None = None,
                          source_bytes: int | None = None,
                          exclude_corner: int | None = None) -> int:
    """The wizard's independence verdict for ONE candidate destination
    against a source (and, with --job, the job's existing corners — the
    simple form checks source vs candidate only). Read-only. Exits by
    verdict; JSON on stdout.

    M5.5 (addendum §1, pair the information with the choice): the same
    JSON carries `capacity` — the source's measured size paired with the
    destination's measured free space (verdict pass/warn/refuse/unknown
    + the ratio). --source-bytes passes the wizard's cached engine
    measure from step 0 (fast path); without it the engine measures the
    source itself. Either way the number is engine-measured, never
    typed."""
    if transport not in ("local", "ssh"):
        print(json.dumps({"error": f"transport '{transport}' is not implemented "
                                   "(local, ssh)"}))
        return 2
    src_ident = read_local_identity(source)
    if "unreadable" in src_ident:
        print(json.dumps({"error": f"source unreadable: {src_ident['unreadable']}"}))
        return 2
    cand = {"index": "candidate", "transport": transport, "destination": dest}
    cand_ident = corner_identity(cand)
    parts = [{"index": "source", "transport": "local", "identity": src_ident},
             {"index": "candidate", "transport": transport, "identity": cand_ident}]
    # --job: the candidate is checked against the job's existing corners too,
    # so a corner-vs-corner warn (e.g. two ssh corners on one host) surfaces
    # on the wizard's warning screen BEFORE commit, not as a raw rc-5 engine
    # error after the user pressed Continue (M4 finding 10).
    if job_name is not None:
        state = read_state()
        job, _ = find_job(state, job_name)
        if job is None:
            print(json.dumps({"error": f"no such job '{job_name}' in {state_path()}"}))
            return 2
        for c in job.get("corners", []):
            if c.get("index") == exclude_corner:
                continue
            parts.append({"index": c.get("index"),
                          "transport": c.get("transport", "local"),
                          "identity": corner_identity(c)})
    # --also <dest> (repeatable, paired with the --also-transport that
    # precedes it): corners the wizard has accepted in this run but not yet
    # declared — the new-job flow's step 2/3 candidates. Same reason as
    # --job: the pairwise check must see every corner that will exist.
    for extra in (also_parts or []):
        parts.append(extra)
    report = independence_check(parts)
    # M5.5: pair the measured size with the measured free space (addendum
    # §1). The fast path rides --source-bytes (the step-0 measure); the
    # engine measures itself when the caller passed nothing. capacity is
    # unknown when either side is unreadable — never a silent number.
    if source_bytes is None:
        source_bytes = measure(Path(source).expanduser()).get("bytes")
    cap = destination_capacity({"transport": transport, "destination": dest},
                               "wizard-candidate")
    capacity = destination_readiness(cand, source_bytes) if source_bytes is not None else corner_capacity_report(None, cap)
    if capacity["verdict"] in ("refuse", "warn", "unknown"):
        report["findings"].append({"kind": capacity["verdict"], "corners": ["candidate"],
                                   "reason": capacity.get("reason", f"available capacity ratio: {capacity.get('ratio')}"),
                                   "evidence": capacity})
    # Refuse a destination that cannot hold its first copy; uncertainty blocks setup.
    kinds = {f["kind"] for f in report["findings"]}
    report["verdict"] = next((v for v in ("refuse", "unknown", "warn") if v in kinds), "pass")
    out = {"verdict": report["verdict"], "findings": report["findings"],
           "candidate": {"transport": transport, "destination": dest,
                         "identity": cand_ident},
           "capacity": capacity}
    print(json.dumps(out))
    return VERDICT_EXIT[report["verdict"]]


